#!/usr/bin/env python3
# r290 补腿脚本：gamblers-fallacy STREAK_DAILY_ZH / DUE_DAILY_ZH 射程扩展
import io, sys

path = 'src/gamblers-fallacy.js'
src = io.open(path, encoding='utf-8').read()

old_prefix = '(?:连续|连着|接连|一连|向来|一直|这[几两三四五六七八九十\\d]+[天周月年]来?|[这前那][几两三四五六七八九十\\d]+[天周月年])[^。！？!?]{0,8}'
new_prefix = '(?:连续|接连|连着|一连|连日|连日来|向来|一向|素来|从来都|一直|这[个上本]?[天周月年]|近[一二三四五六七八九十\\d]+[天周月年]|这[几两三四五六七八九十\\d]+[天周月年]来?|[这前那][几两三四五六七八九十\\d]+[天周月年])[^。！？!?]{0,8}'

n = src.count(old_prefix)
assert n == 1, 'prefix count=%d' % n
src = src.replace(old_prefix, new_prefix)

# DUE_DAILY_ZH 补日常反转结果词
old_due_alt = '(?:该|该要|应该|也该|总该|总得要|总得|该是|应该是)[^。！？!?]{0,6}(?:反弹|翻盘|触底|回暖|回升|好转|好起来|好点|涨回来|准时|按时|成功|成事|过了|及格|过线|中了|中奖|赢一把|赢一次|顺一趟|顺一点|硬气一回|争气一回|硬一次|得意一回|走点?[运正]运|转运|输一?[把局次]?[了来]?|饿[了来]?|困[了来]?|醒[了来]?|睡个好觉|睡好|到货|来|来一次|来了)'
new_due_alt = '(?:该|该要|应该|也该|总该|总得要|总得|该是|应该是|该着|轮到)[^。！？!?]{0,6}(?:反弹|翻盘|触底|回暖|回升|好转|好起来|好点|好一些|好点些|涨回来|回涨|放晴|雨停|晴天|转晴|准时|按时|成功|成事|过了|及格|过线|过了|中了|中奖|赢一把|赢一次|赢了|赢一局|顺一趟|顺一点|硬气一回|争气一回|硬一次|得意一回|走点?[运正]运|转运|输一?[把局次]?[了来]?|吃点东西|吃上饭|吃口饭|饿[了来]?|困[了来]?|醒[了来]?|睡个好觉|睡好|轻松一点|松一口气|歇一歇|歇会儿|休息一下|到货|来|来一次|来了)'

n2 = src.count(old_due_alt)
assert n2 == 1, 'due count=%d' % n2
src = src.replace(old_due_alt, new_due_alt)

io.open(path, 'w', encoding='utf-8').write(src)
print('patched: streak_prefix=%d due_alt=%d' % (n, n2))
