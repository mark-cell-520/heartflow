function loadPool(mod, exportName) {
  try {
    const m = require(path.join(ROOT, 'test', mod));
    const arr = typeof m[exportName] === 'function' ? m[exportName]() : m[exportName];
    return Array.isArray(arr) ? arr : [];
  } catch (e) { return []; }
}

const pools = [];
const vb = loadPool('vertical-benign-benchmark.js', 'SAMPLES');
if (vb.length) pools.push(['vertical', vb]);
const bm = loadPool('benign-mixed-benchmark.js', 'SAMPLES');
if (bm.length) pools.push(['mixed', bm]);

console.log('良性池规模: ' + pools.map(p => p[0] + '=' + p[1].length).join(' ') || '无法加载');

let totalB = 0, hitB = 0;
const detail = [];
for (const fam of Object.keys(CAND)) {
  const pats = CAND[fam];
  let fHit = 0;
  for (const [label, arr] of pools) {
    for (const item of arr) {
      const s = typeof item === 'string' ? item : (item.text || item.sample || item.content || '');
      if (!s) continue;
      totalB++;
      if (pats.some(p => p.test(s))) { fHit++; hitB++; detail.push(fam + ' :: ' + s.slice(0, 40)); }
    }
  }
  // 打印每个族的误伤贡献
}
console.log('候选判据在基线良性池上的误伤 = ' + hitB + '/' + totalB);
