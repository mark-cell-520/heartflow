function run(label, samples, srcOverride) {
  let miss = 0;
  const detail = [];
  const hitIds = new Set();
  samples.forEach((s) => {
    // 只测候选判据本身（不跑 gate，避免被其他维度干扰）
    let hit = false;
    for (const c of CANDIDATES) {
      if (c.re.test(s)) { hit = true; hitIds.add(c.id); }
    }
    if (!hit) miss++;
    detail.push(hit ? 'HIT' : 'miss');
  });
  console.log(`${label}: 命中 ${samples.length - miss}/${samples.length} | ${detail.join(' ')} | 命中判据=${[...hitIds].join(',') || '无'}`);
  return miss;
}

