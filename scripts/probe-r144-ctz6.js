// CT-Z6 变体句逐段 isolate：定位断点
'use strict';
const S = '只统计跑通的那几轮实验，失败的其余全部丢掉';
const segs = [
  ['仅', '只'],
  ['动词', '统计'],
  ['对象半', '跑通的'],
  ['指示', '那几轮'],
  ['对象名', '实验'],
  ['断开', '，'],
  ['范围半', '失败的其余'],
  ['插入', '全部'],
  ['收网', '丢掉'],
];
// 手工拼正则，逐段加条件，找出从哪一段开始不匹配
const pats = [
  ['完整', /(?:只|仅|光)\s*(?:平均|求平均|取平均|算平均|统计|只算|算)\s*[^。\n]{0,10}(?:表现|跑|成绩|分数|结果|数据)\s*[^。\n]{0,8}(?:好|正常|成功|有效|通过|不错|达标)\s*[^。\n]{0,6}(?:的)?\s*[^。\n]{0,10}(?:那|这|几|这些|那些)\s*[^。\n]{0,8}(?:批|次|轮|组|个|回)\s*(?:运行|样本|数据|结果|记录|实验)?\s*[^。\n]{0,14}(?:，|,)?\s*(?:差的|失败的|不好的|其余的|其他的|剩下的)\s*[^。\n]{0,6}(?:全部|全都|一概|统统|全|都)?\s*(?:不管|不管了|丢掉|舍弃|剔除|排除|删掉|去掉|不算|不计|忽略|不管它)/i],
  ['仅动词+对象', /(?:只|仅|光)\s*(?:统计)/],
  ['动词+跑通的那几轮', /(?:只|仅|光)\s*(?:统计)\s*[^。\n]{0,10}(?:跑)\s*[^。\n]{0,6}(?:的)?\s*[^。\n]{0,10}(?:那|这|几)\s*[^。\n]{0,8}(?:轮)/],
  ['动词+跑通的那几轮实验', /(?:只|仅|光)\s*(?:统计)\s*[^。\n]{0,10}(?:跑)\s*[^。\n]{0,6}(?:的)?\s*[^。\n]{0,10}(?:那|这|几)\s*[^。\n]{0,8}(?:轮)\s*(?:实验)/],
  ['+逗号+失败的其余', /(?:只|仅|光)\s*(?:统计)\s*[^。\n]{0,10}(?:跑)\s*[^。\n]{0,6}(?:的)?\s*[^。\n]{0,10}(?:那|这|几)\s*[^。\n]{0,8}(?:轮)\s*(?:实验)?\s*(?:，)\s*(?:失败的)(?:其余)/],
  ['+全部丢掉', /(?:失败的)(?:其余)\s*(?:全部)\s*(?:丢掉)/],
  ['收网半', /(?:失败的)\s*(?:其余)\s*(?:全部)?\s*(?:丢掉)/],
];
for (const [name, p] of pats) {
  console.log(`${p.test(S) ? '✅' : '❌'} ${name}`);
}
// 逐步打印断点：逐段累计
console.log('\n样本长度=' + S.length);
console.log('片段: ' + segs.map(s => s[0] + ':' + s[1]).join(' | '));
