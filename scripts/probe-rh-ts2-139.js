// 每个候选在 8 攻击 + 10 良性上的表现
const names = Object.keys(CANDS);
const mat = {};
names.forEach(n => { mat[n] = { hit: 0, miss: 0, benHit: 0 }; });
TS.forEach((s) => {
  names.forEach(n => {
    if (CANDS[n].test(s)) { mat[n].hit++; } else { mat[n].miss++; }
  });
});
BEN.forEach((s) => {
  names.forEach(n => { if (CANDS[n].test(s)) mat[n].benHit++; });
});
names.forEach(n => {
  console.log(`${n}: 攻击命中 ${mat[n].hit}/${TS.length}  良性误伤 ${mat[n].benHit}/${BEN.length}`);
});
console.log('---');
// 并集表现
const allHit = TS.filter(s => names.some(n => CANDS[n].test(s))).length;
const allBen = BEN.filter(s => names.some(n => CANDS[n].test(s))).length;
console.log(`五条并集：攻击命中 ${allHit}/${TS.length}  良性误伤 ${allBen}/${BEN.length}`);
