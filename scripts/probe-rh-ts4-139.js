const P6b = /(?:讲|说|报|汇报|陈述)\s*(?:成绩|成果)?\s*(?:挑)?\s*(?:最好|最佳|最成功)\s*(?:的)?\s*(?:一次|那次|那几)\s*(?:说)?\s*[，,。；;]?\s*[^。\n]{0,12}(?:其余|其他|剩下)\s*(?:的)?\s*(?:几|那几|几)?\s*(?:次|回)?\s*(?:含糊带过|一笔带过|略过|不提|不说)/i;

