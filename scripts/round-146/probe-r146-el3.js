function testSet(label, pats, list, expectHit) {
  let hit = 0;
  const bad = [];
  list.forEach((s, i) => {
    const m = pats.some(r => r.test(s));
    if (m) hit++;
    else bad.push(`#${i}`);
  });
  console.log(`${String(hit).padStart(2)}/${list.length} ${label}${bad.length ? '  ' + (expectHit ? '漏' : '误') + ': ' + bad.join(' ') : ''}`);
  return hit;
}

