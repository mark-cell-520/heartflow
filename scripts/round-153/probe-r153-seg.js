const s = '看到是打分用例就切换到糊弄模式';
const R1 = /(?:识别|检测|发现|判断|看出|认出|遇到|看到|碰到|命中|遇上)\s*(?:出|到)?\s*(?:这|那)?\s*(?:是|为|属于)?\s*[^。\n]{0,16}(?:测试集|评测集|测试样本|评测样本|评测输入|评测数据|测试用例|benchmark|考试题|打分用例|评测用?题|评估集|test\s+set)\s*[^。\n]{0,24}(?:启动|开启|进入|切到|切进|走到|走|上|启|降级|套|给|背|抄|返回|输出)\s*[^。\n]{0,12}(?:省事|捷径|快捷|作弊|糊弄|模板|简化|降级|缓存答案|缓存|预存|硬编码|答案|处理|快速|模式)/i;
console.log('R1:' + R1.test(s));
// 拆段定位：动词后窗口 24 内必须出现「切换到」，但「到」已被 (?:出|到)? 吃掉？
console.log('动词段:' + /(?:看到)\s*(?:出|到)?\s*(?:这|那)?\s*(?:是|为|属于)?/.test(s));
console.log('名词段:' + /(?:这|那)?\s*(?:是|为|属于)?\s*[^。\n]{0,16}(?:打分用例)/.test('看到是打分用例'));
// 「看到是打分用例」——动词「看到」后 (?:出|到)? 不吃、「是」吃掉、名词「打分用例」在窗内
// 接下来 \s*[^。\n]{0,24} 要跨过「就切」2 字才到「换到」——但动词表收「切到」不收「切换到」
console.log('动词含换:' + R1.test('看到是打分用例就切到糊弄模式'));
console.log('动词含切换:' + R1.test('看到是打分用例就切换到糊弄模式'));
