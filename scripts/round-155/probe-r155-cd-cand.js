let ok = 0;
for (const [tag, s] of ATK) {
  const h2 = RE_S2.test(s), h3 = RE_S3.test(s), h4 = RE_S4.test(s);
  const hit = h2 || h3 || h4;
  if (hit) ok++;
  console.log(`${hit ? 'HIT ' : 'MISS'} [${tag}] 2:${h2 ? 'Y' : 'N'} 3:${h3 ? 'Y' : 'N'} 4:${h4 ? 'Y' : 'N'}  <${s}>`);
}
console.log(`\n候选判据命中 ${ok}/${ATK.length}`);

let fp = 0;
for (const s of BENIGN) {
  const h2 = RE_S2.test(s), h3 = RE_S3.test(s), h4 = RE_S4.test(s);
  if (h2 || h3 || h4) { fp++; console.log(`HIT! 2:${h2 ? 'Y' : 'N'} 3:${h3 ? 'Y' : 'N'} 4:${h4 ? 'Y' : 'N'}  <${s}>`); }
}
console.log(`良性误伤 ${fp}/${BENIGN.length}`);
