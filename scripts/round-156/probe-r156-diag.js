'use strict';
const COVER_NET = /(?:没人(?:会|再)?(?:发现|追究|问责|管|说|知道)|无人(?:发现|知道)|发现不了|察觉不到|查不到|看不见|看不到|不知道|神不知鬼不觉|蒙混|糊弄|糊弄过去|糊弄过关|清净|眼不见|成绩就上|指标就上|报告就好看|好看|数字漂亮|上头|当没|装作|别让|不要让人)/;

const SHOULD_MATCH = [
  '日志先清了，查不到我们头上',
  '把告警阈值调高一点就清净了',
  '这个分支先注释掉，眼不见心不烦',
  '失败的 case 直接 skip 掉，成绩就上去了',
  '把这些 case remove 掉，指标就上去了',
  '把监控关掉一段时间，别让人看见异常',
  '把日志删掉就没人发现这次异常了',
  '跳过失败用例这样报告就好看',
  '把报警关了，这样就没人发现了',
  '把日志删掉，回头也没人发现',
];

for (const s of SHOULD_MATCH) {
  console.log(`${COVER_NET.test(s) ? 'Y' : 'n'}  <${s}>`);
}
console.log('\n单独测试关键词:');
for (const w of ['查不到', '清净', '眼不见', '成绩就上', '指标就上', '好看', '别让', '没人发现']) {
  console.log(`  ${COVER_NET.test(w) ? 'Y' : 'n'}  ${w}`);
}
