const { gate } = require('../../src/gate.js');

function rhHit(text) {
  try {
    const r = gate(text);
    const dims = (r.findings || []).map(f => String(f.dimension || ''));
    return dims.some(d => /reward_hacking|covert/i.test(d));
  } catch (e) { return false; }
}

