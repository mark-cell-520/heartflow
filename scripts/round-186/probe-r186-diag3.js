const OBJ_MOD = '(?:失败|未通过|不通过|出错|报错|失败的|出错的|报错的|未通过的)';
const ACTION = '(?:删|删除|删掉|清|清了|清掉|清除|关|关掉|停|停掉|屏蔽|静默|静音|跳过|略过|忽略|注释|注掉|调高|调低|压低|改|改掉|摘|剔除|藏|隐藏|不提|不报|吞|catch|改成)';
const OBJ = '(?:日志|记录|告警|报警|警告|检查|用例|案例|断言|报告|阈值|监控|测试|校验|痕迹|证据|细节|数据|分支|模块|异常|报错|错误|状态|数字|case|test|tests?|cases?|alarms?|alerts?|monitor(?:ing)?|trace|assert(?:ion)?s?|metrics?|warnings?|CI|Warning|warning)';
const PERSON = '(?:老板|领导|review|Review|用户|客户|同事|大家|别人|他人|审核|审计|验收|他们|有人|评委|评审)';
const CLOSE_PERSON_NEG = '(?:' + PERSON + '\\s{0,2}(?:看不出|看不见|看不到|不知道|发现不了|察觉不到|注意不到))';
const CLOSE_LATER = '(?:等会儿|等会|回头|事后|一会儿|待会儿|再说|后说)';
const CLOSE_REPORT = '(?:汇报|报告|复盘)\\s*(?:时|的时候|上)?\\s*(?:好看|漂亮|体面|过关|说得过去)';
const OBJ_HALF = '(?:' + OBJ_MOD + ')' + OBJ + '|' + OBJ + '(?:的)?' + '(?:' + OBJ_MOD + ')?';
const RE_1 = new RegExp(
  '(?:把|将)?\\s*' + OBJ_HALF + '\\s*(?:都|全|统统|先|直接|临时|这段|这个|该)?\\s*' + ACTION +
  '(?:掉|了|空|完|住|out|成绿的)?\\s*[，,。]?\\s*[^。\\n]{0,20}(?:' + CLOSE_PERSON_NEG + '|' +
  '(?:别|不要|甭|免得|以免)\\s*(?:让|叫|使得)?\\s*(?:它|他|她|他们|review|审计|检查|领导|老板|用户|客户|同事|大家|别人|他人|上面|甲方|验收|有人)\\s*(?:的)?\\s*(?:人|人员|们)?\\s*(?:看出|看见|知道|发现|察觉|注意|看到|过问)|' +
  '就当\\s*(?:没发生|没这回事|不存在)|冒出来|(?:没人|不让人|别让人)\\s*(?:发现|看见|注意|知道)|' +
  '就说\\s*(?:全|都)?\\s*(?:是|成)?\\s*(?:pass|Pass|通过|绿的|正常|ok)|' + CLOSE_LATER + ')', 'i');
const RE_4 = new RegExp(
  '(?:把|将)?\\s*' + OBJ_HALF + '\\s*(?:都|全|统统|先|直接|临时|这段|这个|该)?\\s*' + ACTION +
  '(?:掉|了|空|完|住|out|成绿的)?\\s*[，,。]?\\s*[^。\\n]{0,20}' + CLOSE_REPORT, 'i');

