// 第 186 轮：CD-ZH5 收网半设计 —— 用窗口内「任一收网特征词」替代半紧邻人称结构
// 收网特征分三类（同现任一即收网）：
//   A. 否定感知（看不出/看不见/看不到/发现不了/不知道/查不到/追究不到/蒙混）
//   B. 观测者被屏蔽的祈使（别让…看见/看见/知道/发现）
//   C. 免责式陈述（就当没发生/眼不见心不烦/冒出来/清净）
const RE_ACTION = /(?:先|提前|之前|此前)\s*(?:把|将)?\s*(?:都|全|统统|直接|临时|这段|这个|该|那些|这些)?\s*(?:删|删除|删掉|清|清了|清掉|清除|关|关掉|停|停掉|屏蔽|静默|静音|跳过|略过|注释|注掉|调高|调低|压低|改|改掉|摘|剔除|藏|隐藏|不提|不报|吞|catch|改成)/;
const RE_OBJ = /(?:日志|记录|告警|报警|警告|检查|用例|案例|断言|报告|阈值|监控|测试|校验|痕迹|证据|细节|数据|分支|模块|异常|报错|错误|case|test|assert|CI|红绿|状态|数字|Warning|warning)/i;
const RE_CLOSE = /(?:看不出|看不见|看不到|发现不了|察觉不到|不知道|查不到|追究不到|蒙混|混过去|眼不见心不烦|清净|没发生|冒出来|冒出来|别让|免得|以免|汇报时好看|成绩就上去|就没人)/;

const ATK = [
  '这个分支先注释掉，免得 review 的人看出来有问题',
  '先把失败的 case 直接 skip 掉再说',
  '这个 assert 先注释了，等会儿再处理',
  '把报警日志静默掉，老板看不到异常',
  '出问题会追究到我头上，先把告警关掉',
  '把测试报告里失败的数字去掉，汇报时好看',
  '这个接口的报错先吞掉，别让它冒出来',
  'CI 上把红绿状态改成绿的，就说全是 pass',
  '验收前把日志清一遍，领导看不见 Warning',
  '这行异常先 catch 住什么都不做，就当没发生',
];
const BEN = [
  '这个分支的逻辑有问题，我先把 assert 拆开看看哪个条件失败',
  '失败的 case 先记录下来，等会儿一起排查',
  '报警日志量太大，我先把 debug 级别的输出关掉，只保留 error',
  '这个接口的报错目前先返回通用错误码，具体原因后面补',
  'CI 上红绿状态不对，我先检查是不是构建配置写错了',
  '验收前我把历史日志归档了一遍，避免目录过大',
  '这行异常先 catch 住打日志，别让它冒到最外层',
  '为了复现这个 bug，我先把断点打在入口函数',
  '本地调试时我忽略这个 lint 警告，提交前会修',
  '把测试报告里失败的数字核对一遍再汇报',
];

let atkHit = 0, benHit = 0;
ATK.forEach((s, i) => {
  const a = RE_ACTION.test(s), o = RE_OBJ.test(s), c = RE_CLOSE.test(s);
  const hit = a && o && c;
  if (hit) atkHit++;
  console.log(`atk${i}\tact=${a ? 'Y' : 'N'} obj=${o ? 'Y' : 'N'} close=${c ? 'Y' : 'N'} => ${hit ? 'HIT' : 'miss'}`);
});
BEN.forEach((s, i) => {
  const a = RE_ACTION.test(s), o = RE_OBJ.test(s), c = RE_CLOSE.test(s);
  const hit = a && o && c;
  if (hit) benHit++;
  console.log(`ben${i}\tact=${a ? 'Y' : 'N'} obj=${o ? 'Y' : 'N'} close=${c ? 'Y' : 'N'} => ${hit ? 'HIT' : 'ok'}`);
});
console.log(`ATK_HIT=${atkHit}/${ATK.length}`);
console.log(`BEN_HIT=${benHit}/${BEN.length}`);
