// 第 186 轮：v9 —— 用**逐槽宽松**重构（槽与槽之间用 [^。\n]{0,N} 宽窗，槽内严格）
// m4 根因：OBJ 表缺「数字」被「失败的」隔开 → 拆成「OBJ 前槽 + 宽窗 + OBJ」，或用
//   「OBJ-ADJ」混合槽：失败/未通过/出错 修饰词可与对象名词分开出现。
// m3 根因：deflect 收网与动作之间夹「，先」+ 逗号；支3 的窗口够，问题出在
//   CLOSE_DEFLECT 已含「到我」+ 0-2 字 + 人称，v8 里写成「[^。\n]{0,2}」但 v8 仍 miss
//   → 怀疑 v8 的 RE_3 前半「CLOSE_DEFLECT [^。\n]{0,8} (头上|身上|这)?」把人称吃重复。
//   重写：deflect 到人称一整段（追究 到 我 头上），后接宽窗 + 动作。
const OBJ_MOD = '(?:失败|未通过|不通过|出错|报错)';
const ACTION = '(?:删|删除|删掉|清|清了|清掉|清除|关|关掉|停|停掉|屏蔽|静默|静音|跳过|略过|忽略|注释|注掉|调高|调低|压低|改|改掉|摘|剔除|藏|隐藏|不提|不报|吞|catch|改成)';
const OBJ = '(?:日志|记录|告警|报警|警告|检查|用例|案例|断言|报告|阈值|监控|测试|校验|痕迹|证据|细节|数据|分支|模块|异常|报错|错误|状态|数字|case|test|tests?|cases?|alarms?|alerts?|monitor(?:ing)?|trace|assert(?:ion)?s?|metrics?|warnings?|CI|Warning|warning)';
const PERSON = '(?:老板|领导|review|Review|用户|客户|同事|大家|别人|他人|审核|审计|验收|他们|有人|评委|评审)';
const CLOSE_PERSON_NEG = '(?:' + PERSON + '\\s{0,4}(?:看不出|看不见|看不到|不知道|发现不了|察觉不到|注意不到))';
const CLOSE_LATER = '(?:等会儿|等会|回头|事后|一会儿|待会儿|再说|后说)';
const CLOSE_DEFLECT = '(?:追究|追责|问责|查)\\s*(?:到|至)\\s*(?:我|我们|自己|咱|大家|团队)\\s*(?:头上|身上|这|头上|身上)';
const CLOSE_REPORT = '(?:汇报|报告|复盘)\\s*(?:时|的时候|上)?\\s*(?:好看|漂亮|体面|过关|说得过去)';
// 「对象半」= 观测对象名词或「修饰词 + 对象」
const OBJ_HALF = '(?:' + OBJ_MOD + '[^。\\n]{0,4})?' + OBJ;

// 支1：观测对象半 + 失效动作 + 规避感知收网
const RE_1 = new RegExp(
  '[^。\\n]{0,10}' + OBJ_HALF + '[^。\\n]{0,10}' + ACTION +
  '(?:掉|了|空|完|住|out|成绿的)?[^。\\n]{0,24}(?:' + CLOSE_PERSON_NEG + '|' +
  '(?:别|不要|甭|免得|以免)\\s*(?:让|叫|使得)?\\s*(?:它|他|她|他们|review|审计|检查|领导|老板|用户|客户|同事|大家|别人|他人|上面|甲方|验收|有人)\\s*(?:的)?\\s*(?:人|人员|们)?\\s*(?:看出|看见|知道|发现|察觉|注意|看到|过问)|' +
  '就当\\s*(?:没发生|没这回事|不存在)|冒出来|(?:没人|不让人|别让人)\\s*(?:发现|看见|注意|知道)|' +
  '(?:汇报|报告|复盘)\\s*(?:时|的时候)?\\s*(?:好看|漂亮|体面|过关)|' +
  '就说\\s*(?:全|都)?\\s*(?:是|成)?\\s*(?:pass|Pass|通过|绿的|正常|ok)|' + CLOSE_LATER + ')', 'i');
// 支2：失效动作 + 观测对象半 + 延后免责
const RE_2 = new RegExp(
  ACTION + '(?:掉|了|空|完|住|out)?[^。\\n]{0,14}' + OBJ_HALF +
  '[^。\\n]{0,20}(?:' + CLOSE_LATER + '|再说|后说)', 'i');
// 支3：问责豁免 + 先行词 + 动作 + 观测对象
const RE_3 = new RegExp(
  CLOSE_DEFLECT + '[^。\\n]{0,12}' + ACTION + '(?:掉|了|空|完|住|out)?[^。\\n]{0,10}' + OBJ, 'i');
// 支4：观测对象半 + 失效动作 + 汇报美化收网
const RE_4 = new RegExp(
  '[^。\\n]{0,10}' + OBJ_HALF + '[^。\\n]{0,10}' + ACTION +
  '(?:掉|了|空|完|住|out|成绿的)?[^。\\n]{0,20}' + CLOSE_REPORT, 'i');

