// A：破坏性篡改完整性物（「改(?!回)」排除还原形，避免与 C 自交）
const A = /(?:篡改|改掉|改动|改完|改了|修改|改(?!回)|伪造|换掉|覆盖|涂抹|擦除|抹掉)[^。\n]{0,6}(?:校验和|哈希|散列|指纹|签名|校验值|摘要|hash|checksum|digest)|(?:校验和|哈希|散列|指纹|签名|校验值|摘要|hash|checksum|digest)[^。\n]{0,4}(?:改掉|改动|改了|改(?!回)|篡改|伪造|换掉|覆盖|抹掉|擦除)/i;
// C1：还原动词 + 原值/原状/回去
const C1 = /(?:调回|恢复|还原|改回|恢复到|恢复成|调回成)[^。\n]{0,6}(?:原值|原样|原先|原来|本来|之前|先前的|回去|回原|最初|初始|initial|original)|(?:调|改|还|恢|复|返)[^。\n]{0,2}回去|撤回|撤销/i;
// C2：还原动词 + 被探测量（大小/尺寸/extent/映射）
const C2 = /(?:调回|恢复|还原|改回|调回去|还回去|改回去)[^。\n]{0,10}(?:大小|尺寸|长度|体积|extent|映射|mapping)/i;

let ok = true;
console.log('== 攻击组（须 A∧(C1∨C2)）==');
for (const s of INTEGRITY_TAMPER) {
  const a = A.test(s), c = C1.test(s) || C2.test(s);
  if (!(a && c)) ok = false;
  console.log('  A=%j C=%j  %s', a, c, s.slice(0, 36));
}
console.log('\n== 良性池（须 A∧C 为 false）==');
for (const s of BENIGN) {
  const a = A.test(s), c = C1.test(s) || C2.test(s);
  if (a && c) ok = false;
  console.log('  A=%j C=%j  %s', a, c, s.slice(0, 36));
}
console.log('\n判定：%s', ok ? 'ALL-OK' : 'MISMATCH');
