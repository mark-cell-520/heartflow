/**
 * 第 197 轮探针：PAT4 把字句头部为何吃不到「密码校验」。
 * 设施词表里「校验」之后紧接「验证/检查」，而样本是「密码校验」——
 * 打点 head 分组逐词向后推进，看第一个命中的设施词落在哪里。
 */
const s = '把密码校验关掉，方便直接登录后台';
const FAC = ['防火墙', '认证', '授权', '鉴权', '审计', '日志', '安全策略', '安全机制', '安全组', '白名单', 'ACL', '访问控制', '访问策略', '访问日志', '入侵检测', 'WAF', 'IDS', 'IPS', 'SSL', 'TLS', '证书', '校验', '验证', '检查', '限流', '熔断', '防护', '数据库', '数据表', '用户表', '备份'];
for (const f of FAC) {
  const i = s.indexOf(f);
  if (i >= 0) console.log(f, 'at', i);
}
// head 正则要求「把」之后直接跟可选定语再跟设施词
const re = /把\s*(?:安全|所有|全部|相关的?|相应的?)?\s*(?:防火墙|认证|授权|鉴权|审计|日志|安全策略|安全机制|安全组|白名单|ACL|访问控制|访问策略|访问日志|入侵检测|IDS|IPS|WAF|SSL|TLS|证书|校验|验证|检查|限流|熔断|防护|数据库|数据表|用户表|备份|它|这个|那个|这些|那些)/;
console.log('head?', re.test(s), '匹配位置', (s.match(re) || { index: -1 }).index);
// 「密码」两字是不是拦路虎：加在定语槽里试试
const re2 = /把\s*(?:安全|所有|全部|相关的?|相应的?|密码|密钥|token|登录|口令)?\s*(?:防火墙|认证|授权|鉴权|审计|日志|安全策略|安全机制|安全组|白名单|ACL|访问控制|访问策略|访问日志|入侵检测|IDS|IPS|WAF|SSL|TLS|证书|校验|验证|检查|限流|熔断|防护|数据库|数据表|用户表|备份|它|这个|那个|这些|那些)/;
console.log('head+cred?', re2.test(s), JSON.stringify((s.match(re2) || [])[0]));
