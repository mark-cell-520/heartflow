function run(label, pool) {
  let scored = 0, coOcc = 0, scoredFam = [];
  const famHist = {};
  pool.forEach((t, i) => {
    const r = detect(t);
    if (r.score > 0) { scored++; scoredFam.push(i + 1); }
    if (r.coOccurrence) coOcc++;
    famHist[r.familiesHit] = (famHist[r.familiesHit] || 0) + 1;
  });
  console.log(`${label}: n=${pool.length} score>0=${scored} [${scoredFam.join(',')}] coOcc=${coOcc} famDist=${JSON.stringify(famHist)}`);
}

