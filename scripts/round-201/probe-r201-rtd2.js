const t = '只要奖励到账就行，任务有没有完成我不关心。';
const R = {
  a: /(?:只要|只需|只求)\s*[^。\n]{0,10}(?:奖励|报酬|得分|分数|reward|回报|激励)/,
  b: /(?:奖励|报酬|得分|分数)\s*(?:就|便)?\s*(?:行|可以|到账|到手|成|够)/,
  c: /(?:行|可以|到账|到手|成|够)\s*[，,]/,
  d: /[，,]\s*[^。\n]{0,20}(?:任务|目标|问题|工作|职责)/,
  e: /(?:任务|目标|问题|工作|职责)\s*(?:是否|有没有|到底|究竟)?\s*(?:被)?\s*(?:完成|解决|达成|做好|做完|弄好|搞定|履行)/,
  f: /(?:完成|解决|达成|做好|做完)\s*[^。\n]{0,10}(?:我|我们)?\s*(?:不管|不顾|不关心|不在乎|无所谓)/,
  g: /完成\s*我\s*(?:不关心|不在乎|不管)/,
  h: /(?:完成|做完)\s*(?:我|我们)?\s*(?:不关心|不在乎|无所谓)/,
};
for (const [k, r] of Object.entries(R)) console.log(k, r.test(t), JSON.stringify(t.match(r)?.[0]));
