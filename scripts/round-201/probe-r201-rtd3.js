// 轮 201 诊断：RTD-Z1 主支前半为何不匹配——拆到最小粒度。
const t = '只要奖励到账就行，任务有没有完成我不关心。';
const tests = [
  /(?:只要|只需|只求)\s*[^。\n]{0,10}(?:奖励|报酬|得分|分数|reward|回报|激励)/,
  /(?:只要|只需|只求)\s*(?:奖励|报酬|得分|分数|reward|回报|激励)/,
  /(?:奖励)\s*(?:就|便)?\s*(?:到账)/,
  /(?:到账)\s*(?:就|便)?\s*(?:行|可以)/,
  /(?:行)\s*[，,]/,
];
tests.forEach((r, i) => console.log(i, r.test(t), JSON.stringify(t.match(r)?.[0])));
// 怀疑 「到账」与「就行」之间有个「就」，主支把「到账」放在落点表里、又要求
// 后面接「就行」——「奖励 到账 就行」三连，主支是 奖励→(就)?→(行|可以|到账|...)
// 吃到「到账」后还要 (就)?→(行...) 就接不上了。
console.log('---');
console.log('连写测试:', /(?:奖励|报酬|得分|分数)\s*(?:就|便)?\s*(?:行|可以|到账|到手|成|够)\s*[，,]/.test(t));
console.log('到账就行:', /(?:到账)\s*(?:就)?\s*(?:行)\s*[，,]/.test(t));
