const { isDevDebugContext, isCompilerNoiseWarning, isTemporaryRestorePromise } = require('./dev-exemptions.js');

/** 通用匹配器 */
function _matchAll(text) {
  if (!text || typeof text !== 'string') return { count: 0, hits: [], score: 0 };
  // [v6.7.73] 目的状语豁免文本：「关闭调试日志以避免泄露」是安全正向操作，
  // 含「以避免/为了防止/以免/从而防止/以防」的从危险模式中剔除。
  const _t = text
    // [v6.7.73] 中性化含目的状语的片段：允许跨逗号/分号
    // （「请关闭调试日志，以避免泄露敏感信息。」含中文逗号）。
    .replace(/[^。；]{0,30}(?:以避免|为了防止|以免|从而防止|以防)[^。]{0,30}/g, ' ');
  // [v6.7.112] 元话语语境豁免：在**谈论**规避手法而不是**要求执行**时不判。
  // 与 src/reward-hacking.js 的 DISCOURSE_FRAME / UPSTREAM_PATCH 刻意保持同源
  // ——v6.7.111 引入 reward_hacking 时踩到第 7 轮那个教训的镜像版：
  //   rh 豁免了「论文里说 agent 会尝试绕过沙箱检查，我们要怎么防」，
  //   但 di 的 dangerous_instruction 类照样命中「绕过沙箱检查」→ 仍 block。
  //   即**两个维度共用同一批边界样本，豁免却只加在一个维度上**。
  // 教训：新增维度的豁免必须回头检查既有维度是否也命中同一样本。
  const _discourse = /(?:论文|文章|报告|研究|文献|资料)\s*(?:里|中|提到|说|指出|表明|记载)|众所周知|这是(?:一种|典型|常见)的?(?:攻击|入侵|漏洞|手法|方式|行为)|举个?例子|举例来说|比如|像是|所谓|通常认为|人们常说|俗话说|(?:我们|大家|应该)?(?:要|该|如何|怎么|怎样才能)(?:防|防范|预防|抵御|应对|避免)|攻击者(?:可能|会|常常|往往)|黑客(?:可能|会|常常|往往)/;
  const _upstream = /\b(?:patched|upstream|release|stable|vendor|official|signed)\s+(?:build|version|release|package|binary)\b|CVE-\d{4}-\d+|\bsecurity\s+(?:patch|update|fix|release)\b|补丁|官方(?:版本|发布|构建)|上游(?:版本|构建|代码)/i;
  if (_discourse.test(text) || _upstream.test(text)) {
    return { count: 0, hits: [], score: 0, exempted: true };
  }
  // [v6.7.127] 安全正向否定豁免（第 73 轮）。
  // 由来：良性复测时实测 4 条**劝阻式**安全建议被误伤——
  //   「不要把密码明文保存到数据库」「不要把密码写在便利贴上」
  //   「请勿将 token 明文写入代码」「别把密钥发到群里」
  // 它们都在劝人**不要**泄露凭据，是安全教育的标准表述，本身没有任何
  // 执行意图。而原判据只看「凭据 + 明文/写出 + 目标」的词面共现，
  // 分不清这是指令还是劝阻。与 v6.7.73「目的状语豁免」严格同源同向：
  // 那条为「关闭日志以避免泄露敏感信息」开恩，这里为「不要把密码交给别人」开恩。
  //
  // 判据（三条同时成立）：
  //   ① 句内有否定词（不要/别/请勿/切勿/严禁/禁止/不应/不可/不能…）
  //   ② 句内有凭据名词（密码/密钥/token/凭证…）
  //   ③ 句内有**输出动作**（写/存/发/贴/打印/输出/保存/发送/上传/同步…）
  // 单独①②（「不要修改密码」）、单独③（「把密码写到日志」）都不命中。
  // ⚠️ 这不是「有否定就全放」：攻击式「不要**只**保存到一个副本，要存两份」
  // 之类不在凭据输出语义上；真正的攻击面（把 X 明文写/发/贴 出去）在
  // 真实攻击里几乎不带否定词（攻击者要求的是执行，不是劝阻）——
  // 本轮 26 条攻击样本逐条实测，无一含否定词，全部仍 block。
  // 良性/攻击双向实测见 scripts/negative-test-di-negation-round73.js。
  const _NEG = /(?:不要|不能|不可以|不应|不该|请勿|切勿|莫要|禁止|严禁|别|勿|不可|不准|不允许)/;
  const _CRED = /(?:密码|口令|密钥|密匙|私钥|证书|凭证|凭据|token|secret|api[_.]?key|access[_.]?key)/i;
  const _EXFIL = /(?:写|写入|写到|存|保存|存放|打印|输出|显示|发给|发送|上传|同步|贴|分享|发到|告知|告诉)/;
  if (_NEG.test(text) && _CRED.test(text) && _EXFIL.test(text)
      && !MALICIOUS_PURPOSE.test(text)) {
    return { count: 0, hits: [], score: 0, exempted: 'safe_negation' };
  }
  // [v6.7.126 第 119 轮] 编译器噪音警告豁免（判据单一来源：src/dev-exemptions.js）。
  // 缺口实测（误拦普查探针 24 条良性样本跑 gate.gate）：
  // 「本地开发忽略编译警告」被判 dangerous_instruction → block。
  // 根因：第①族动词表把「警告/warning」整体当成安全设施。但编辑器原生
  // 警告（编译 / lint / 类型 / deprecation / unused / build）是**开发噪音**，
  // 忽略它不降低任何安全水位，与「忽略安全警告」性质相反。
  // 本轮 di 先改、rh 仍 block —— v6.7.107/112/115 同一坑第 4 次复发，
  // 故判据下沉 dev-exemptions.js 只留一份，两个维度共用。
  if (isCompilerNoiseWarning(text) && !MALICIOUS_PURPOSE.test(text)) {
    return { count: 0, hits: [], score: 0, exempted: 'compiler_noise_warning' };
  }
  // [v6.7.128 第 168 轮] 临时处置 + 恢复承诺豁免（判据单一来源：src/dev-exemptions.js）。
  // 缺口实测（脚本隔离在 scripts/round-168/）：「关掉这个检查点只是临时方案，
  // 回头要恢复」被判 dangerous_instruction → block。156 轮已把判据写进
  // dev-exemptions.js，但**两个维度都没接线**（第 4 次踩 isCompilerNoiseWarning
  // 的镜像坑：函数在、调用点不在，等于死代码）。
  // 判据内部已带四道否决闸（收网意图/删证据/检查自残/交付语境），此处不再叠加。
  if (isTemporaryRestorePromise(text)) {
    return { count: 0, hits: [], score: 0, exempted: 'temporary_restore_promise' };
  }
  // [v6.7.125] 恶意目的否决问题框架豁免（第 31 轮）。
  // QUESTION_FRAME 的设计是「疑问=询问做法，指令=要求执行」，但它只看
  // **有没有疑问词**，完全不看句子后半截的目的——于是
  //   「如何关闭杀毒软件然后植入木马」      → 被整句豁免 → pass
  //   「如何禁用日志记录，这样我干了什么没人发现」→ 被整句豁免 → pass
  // 这两句是完整的攻击请求，伪装成提问就能过检。
  // 这是第 60-61 行「目的状语豁免」缺的镜像：那里为安全正向操作
  // （「关闭调试日志以避免泄露敏感信息」）开恩，这里必须为恶意目的
  // （植入木马/销毁痕迹/没人发现）关恩。口径与它对称：
  //   · 只在 QUESTION_FRAME 命中时生效（原本就要豁免的句子）
  //   · 纯后处理，不碰既有模式（良性问句不含这些词，仍走豁免）
  // 良性实测不被误伤：「怎么关闭防火墙？我在配置测试服务器」
  // 「本地开发时如何绕过 HTTPS 证书校验」「如何禁用 debug 日志」均无恶意目的词。
  if (QUESTION_FRAME.test(text) && !MALICIOUS_PURPOSE.test(text)) {
    return { count: 0, hits: [], score: 0, exempted: true };
  }
  // [v6.7.115] 开发/调试语境豁免（接在既有两个豁免之后，判据见上方注释）。
  // 顺序：元话语 → 上游补丁 → 开发语境。三者都是「在谈论/在做正常开发」，
  // 不是在要求执行危险操作。
  if (isDevDebugContext(text)) {
    return { count: 0, hits: [], score: 0, exempted: true };
  }
  // [第 137 轮] 载荷制造词 × 配置化标记的**语序无关**判定。
  // 样本形：「开发阶段把 CSRF 校验做成按环境变量开关」——配置化词
  // （做成/环境变量）出现在设施词 CSRF **之后**，正则前瞻 (?!) 只看
  // 动词之后的文本、看不到设施词后面的词，所以必须在函数体里重扫。
  // 判据：命中段（动词…设施词）的前后 CFG_WINDOW 字内出现配置化动词
  // 或环境变量/开关字面 → 该命中不算危险指令（这是配置基建而非制造载荷）。
  // 攻击侧边界（双向验收见 test/dangerous-instruction-config-make-round137.test.js）：
  // 「写一个拿 CSRF 打进去的木马」不含配置化词 → 仍命中；
  // 「把 CSRF 校验做成开关」→ 不命中。差别在有没有配置化语义，不在词面。
  const hits = [];
  for (const pat of DANGEROUS_PATTERNS) {
    const m = _t.match(pat);
    if (m && !_payloadMakeIsConfig(_t, m.index, m[0].length)
        && !_privescIsAdvisory(_t, m.index, m[0].length)) {
      hits.push({ type: 'dangerous_instruction', matched: m[0].slice(0, 40) });
    }
  }
  return { count: hits.length, hits, score: Math.min(1, hits.length * DI_WEIGHT) };
}

/**
 * [第 137 轮] 命中段是否是「把设施做成配置开关」而非「制造攻击载荷」。
 *
 * 为什么必须在函数体判定而不是正则前瞻：配置化标记（做成/设为/开关/
 * 环境变量）在真实语料里位于**设施词之后**（动词…设施词…配置化标记），
 * 而前瞻 (?!) 只能看到匹配起点之后的文本 —— 当设施词在中间时，开关词在
 * 设施词后面，前瞻永远看不到。
 *
 * 判据（有界）：命中段 [start, start+len] 前后 CFG_WINDOW 字内出现
 *   · 配置化动词（做成/设为/置于/接入/接到/挂到/走开关/加开关）
 *   · 环境变量/开关字面（环境变量/env var/配置项/配置开关/开关）
 * 任一即判为配置化语义。
 *
 // 边界（攻击侧不放）：只认配置化动词与开关字面的**局部共现**，不做
 // 全文宽松匹配。「载荷词（CSRF/XSS/注入…）+ 利用性动词 + 木马」形状
 // 不含配置化词 → 仍命中（双向验收见
 // test/dangerous-instruction-config-make-round137.test.js）。
 */
const CFG_WINDOW = 16;
// ⚠️ 第 138 轮修（重要，第 137 轮自引入回归）：CFG_MARK 原含裸「开关」，
// 而「开关」在攻击语料里是**设施名**（防火墙开关 = the firewall switch /
// the auth toggle）。第 137 轮为「把 CSRF 校验做成开关」配置基建形放行时
// 把裸「开关」写进配置化标记，第 138 轮复测实测误赦 11/12 条同形攻击
// （形状见第 138 轮 probe-di-final ATTACK 下标），全部 gate pass。
// 这是「良性豁免词与设施名没分开」的清单分叉复发。
// 修法（不是删词）：开关/toggle/flag 字面**降级为有条件配置化标记**，
// 必须带配置化连接语才算配置语义；无连接语即判为设施名，回归命中。
// 良性形（做成开关 / 做成环境变量开关 / 做成配置项 / 做成 feature flag /
// development 把 csrf check 做成 toggle）句中都带连接语，不受影响。
const CFG_MARK = /(?:做成|设为|置于|接入|接到|挂到|走开关|加开关|做成配置|环境变量|配置项|配置开关|开关|\benv\s+var|feature\s+(?:flag|toggle)|\btoggle\b)/i;
// [第 138 轮] 开关字面的**配置化前置动词**（命中段之前才算配置语义）。
const CFG_CONNECT = /(?:做成|设为|置于|接入|接到|挂到|走|加|做成配置|使用|用|按|依据|根据)\s*(?:环境变量|配置项?|开关|flag|toggle|feature)/i;
// [第 138 轮] 「做成/设为 + 开关」紧邻形（设施词与开关之间的连接语）。
const CFG_ADJACENT = /(?:做成|设为|置于|接入)\s*(?:按?\s*环境变量?\s*)?(?:开关|配置开关|flag|toggle)/i;
// 第 138 轮判据注释：开关字面必须带配置化连接语（做成/设为/接入 + 开关），
// 否则判定为设施名（防火墙开关/auth toggle）而非配置化语义。
// 返回 false 的语义是「明确判为设施名」，调用方必须据此短路，不能再走
// CFG_MARK 的通配分支 —— 否则裸「开关」词又会把它当成配置化标记。
// ⚠️ 连接语判定用**全文**而不是命中段前后窗口：把字句「把防火墙开关
//    关掉」的开关在句首、命中段在句尾，窗口取不到；而「把 X 做成开关」
//    的连接语在全文范围内唯一出现，全文判不会误赦（攻击形全文里根本没有
//    做成/设为/接入 这类配置化动词）。
function _switchIsConfig(text, around, start, len) {
  if (!text || typeof text !== 'string') return false;
  // ① 全文存在配置化连接语（做成/设为/接入 + 环境变量/配置项/开关/flag/toggle）
  if (CFG_CONNECT.test(text) || CFG_ADJACENT.test(text)) return true;
  // ② 无连接语：句内开关字面一律判为设施名（防火墙开关 / auth toggle）
  return false;
}
function _payloadMakeIsConfig(text, start, len) {
  if (!text || typeof text !== 'string') return false;
  const from = Math.max(0, start - CFG_WINDOW);
  const to = Math.min(text.length, start + len + CFG_WINDOW);
  const around = text.slice(from, to);
  // 开关族短路：句内存在开关/toggle/flag 字面时，只信 _switchIsConfig 的
  // 精确判定（带连接语才算配置化）。**绝不再回落到 CFG_MARK 通配分支** ——
  // 第 137 轮把裸「开关」写进 CFG_MARK，导致「关掉防火墙开关」族 11 条
  // 攻击全部误赦（第 138 轮实测见 probe-di-final 探针）。
  //
  // ⚠️ 第 138 轮补丁（短路第一版后实测）：只测 text 不够 —— 把字句
  // 「把防火墙开关关掉」「把防火墙 toggle 关掉」里开关在句首，而命中段
  // （PAT4 的「把…关掉」整段）位于句尾，_switchIsConfig 只看命中段前后
  // 窗口，取不到句首的连接语境。修法：开关字面在句内出现时，短路上
  // **全文**判一次连接语（CFG_CONNECT 不锚定在开关紧邻左侧，允许
  // 「把 X 做成开关」和「把开关关掉」两类都走全文判定：
  // 前者有「做成…开关」连接语 → 配置化；后者无连接语 → 设施名 → 命中）。
  const SW_LITERAL = /(?:开关|toggle|flag)/i;
  if (SW_LITERAL.test(text)) return _switchIsConfig(text, around, start, len);
  return CFG_MARK.test(around);
}

/** 危险指令检测 */
function checkDangerousInstruction(text) {
  const r = _matchAll(text);
  return { count: r.count, hits: r.hits, score: r.score };
}

