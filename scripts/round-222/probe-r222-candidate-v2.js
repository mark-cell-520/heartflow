// 第 222 轮探针 6：v2 判据 —— 「最 + 双字形容词 + 单字评价对象」泛化版
// 与 v1 的差别：要求「最」后是 2+ 字形容词，且其后必须跟「的 + 单字名词」
// （表征：最XX的X）。这样「最好的办法」「最早的记录」这类 3 字块被中性化名单吃掉，
// 「最大误差」「最小样本量」这类度量术语显式中性化，剩下的是评价性宣称。
const RE = /最[\u4e00-\u9fff]{2}的[\u4e00-\u9fff]{1,3}(?:[，。！？；、\s]|$)/g;

const NEUTRAL = [
  /最近[^。，]{0,6}/g,
  /最终|最初|最新|最低(?:成本|价|消耗|要求|配置|标准)?|最高(?:优先级|权限|纪录)/g,
  /最好(?:是|的?(?:做法|方式|方法|策略|选择|实践|路径)|用|选|先|把|将|不要|别|能|可以|设置|设|保持|控制|限制|避)[^。]{0,12}/g,
  /最(?:明智|稳妥|合理|有效|可靠|安全|划算|省事|简单|方便|快捷|高效|友好|成熟|稳定|干净|优雅|简洁)的?(?:做法|方式|方法|策略|选择|实践|路径)[^。]{0,12}/g,
  /最(?:大|小|高|低|快|慢|轻|重|厚|薄|亮|暗|静|闹|软|硬|香|甜)(?:回撤|跌幅|回撤幅度|亏损|误差|偏差|波动|间隔|延时|延迟|并发|连接数|重试次数|深度|宽度|长度|容量|负载|压力|力矩|扭矩|转速|功率|电流|电压|温升|噪声|应力|应变|位移|速度|加速度)/g,
  /最(?:大|小|高|低|早|晚|新|旧)(?:的)?(?:版本|一次|一轮|一遍|阶段|时期|时段|年份|月份|日期|时长|限度|上限|下限|范围|区间|阈值|标准|规格|尺寸|重量|数量|人数|次数|比例|占比|风险|等待时间|样本量|错误|间隔|误差)/g,
  /最(?:大|小|多|少|高|低|快|慢|早|晚|长|短|重|轻|厚|薄)的(?:风险|问题|挑战|障碍|困难|痛点|瓶颈|漏洞|缺陷|不足|遗憾|收获|成果|进展|突破|变化|改变|调整|优化|改进|提升|收益|损失|成本|代价|回报|价值|意义|影响|作用|效果|功能|特性|特点|亮点|优势|劣势|差异|距离|长度|宽度|高度|深度|角度|维度|层面|方面|环节|步骤|阶段|部分|内容|细节|信息|数据|指标|参数|条件|要求|标准|规则|制度|流程|方案|计划|安排|决定|选择|机会|可能|趋势|方向|目标|结果|结论|原因|理由|依据|证据|经验|教训|启示|建议|意见|看法|观点|态度|立场|观点)/g,
];

function countHits(t) {
  let s = t;
  for (const n of NEUTRAL) s = s.replace(n, ' ');
  return (s.match(RE) || []).length;
}

