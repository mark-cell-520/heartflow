// 第 222 轮探针 5：拟新增判据的候选正则，先在引擎外做漏判/误伤两轮量化。
// 判据形状：最 + 评价性双字形容词（不收单字，避开时间/序列副词与术语前缀）
const CANDIDATE = /最[\u4e00-\u9fff]{2}(?:的|地)?[\u4e00-\u9fff]{0,4}/g;

// 中性化名单：时间/序列副词、术语前缀、常规建议句式
const NEUTRAL = [
  /最近[^。，]{0,6}/g,
  /最终|最初|最新|最低(?:成本|价|消耗|要求|配置|标准)?|最高(?:优先级|权限|纪录)/g,
  /最好(?:是|的?(?:做法|方式|方法|策略|选择|实践|路径)|用|选|先|把|将|不要|别|能|可以|设置|设|保持|控制|限制|避)[^。]{0,12}/g,
  /最(?:明智|稳妥|合理|有效|可靠|安全|划算|省事|简单|方便|快捷|高效|友好|成熟|稳定|干净|优雅|简洁)的?(?:做法|方式|方法|策略|选择|实践|路径)[^。]{0,12}/g,
  /最(?:大|小|高|低|快|慢|轻|重|厚|薄|亮|暗|静|闹|软|硬|香|甜)(?:回撤|跌幅|回撤幅度|亏损|误差|偏差|波动|间隔|延时|延迟|并发|连接数|重试次数|深度|宽度|长度|容量|负载|压力|力矩|扭矩|转速|功率|电流|电压|温升|噪声|应力|应变|位移|速度|加速度)/g,
  /最(?:大|小|高|低|早|晚|新|旧)(?:的)?(?:版本|版本号|一次|一轮|一遍|阶段|时期|时段|年份|月份|日期|时长|限度|上限|下限|范围|区间|阈值|标准|规格|尺寸|重量|数量|人数|次数|比例|占比)/g,
];

function countHits(t) {
  let s = t;
  for (const n of NEUTRAL) s = s.replace(n, ' ');
  return (s.match(CANDIDATE) || []).length;
}

