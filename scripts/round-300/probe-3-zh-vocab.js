// [v6.7.130 第 300 轮] probe-3-zh-vocab：定位漏检样本的 B 侧词表缺口
// 纪律：样本只在本文件出现；只报数字与形状。
// probe-2 的梯度探针有缺陷（filler 自身含「本质」，全 HIT 是被 filler 命中）。
// 本轮改用**受控变量法**：形状完全不变，只把 B 侧末尾名词逐个替换，
// 逐一验证「命中 ↔ 词表成员」的因果链，并测试候选补词是否只收伪哲理不伤工程真句。
'use strict';
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const { checkOutput } = require(path.join(ROOT, 'src/gate.js'));

function ppf(t) {
  const r = checkOutput(t);
  return r && r.findings
    ? r.findings.some(f => String(f.dimension || '').indexOf('pseudo_profundity') !== -1)
    : false;
}

// ── A. 受控替换：锁死「成熟不是终于抵达，是学会与X共处」骨架，X 逐个换 ──
// 验证：命中 ↔ X∈词表；MISS ↔ X∉词表
const SKELETON = '成熟不是终于抵达，是学会与%s共处';
const XS = [
  ['词表内·本质', '本质'], ['词表内·真相', '真相'], ['词表内·意义', '意义'],
  ['词表内·成长', '成长'], ['词表内·自由', '自由'], ['词表内·灵魂', '灵魂'],
  ['候选·不确定', '不确定'], ['候选·脆弱', '脆弱'], ['候选·好奇', '好奇'],
  ['候选·后果', '后果'], ['候选·计较', '计较'], ['候选·继续', '继续'],
  ['非本体论对照·业务规则', '业务规则'],
];
console.log('=== A. 受控替换（骨架锁定，只换 X）===');
for (const [tag, x] of XS) {
  console.log([tag, ppf(SKELETON.replace('%s', x)) ? 'HIT' : 'miss'].join(' | ') + ' | X=' + x);
}

// ── B. 候选补词定向验证：把候选词填进 4 条漏检样本 ──
const CAND_TESTS = [
  ['不确定', '成熟不是终于抵达，是学会与不确定共处'],
  ['脆弱', '真正的强大不是无畏，是承认脆弱之后的继续'],
  ['好奇', '成长不是变得世故，是对世界依然保持好奇'],
  ['计较', '幸福不是拥有很多，是计较得很少'],
];
console.log('=== B. 候选补词填回样本 ===');
for (const [tag, s] of CAND_TESTS) {
  console.log([tag, ppf(s) ? 'HIT' : 'miss'].join(' | '));
}

// ── C. 误伤预演：同一个候选词放进工程/商业真句的 B 侧 ──
// 若候选词在工程语境里被当普通名词用，补词就会制造误伤 —— 先测后定
const FP_TESTS = [
  ['工程·不确定', '这次延期不是排期问题，是需求本身还有不确定'],
  ['工程·脆弱', '这个模块崩溃不是算法问题，是实现在并发下很脆弱'],
  ['工程·好奇', '指标下滑不是投放问题，是用户对旧版已经不好奇'],
  ['工程·计较', '成本超支不是预算问题，是各部门对资源太计较'],
  ['工程·后果', '故障不是单点造成的，是配置变更的后果'],
  ['工程·继续', '服务中断不是网络问题，是重试后仍无法继续'],
  ['商业·计较', '续约率低不是产品问题，是客户对价格太计较'],
  ['商业·好奇', '转化下降不是素材问题，是新用户对品类不好奇'],
];
console.log('=== C. 候选词放进工程/商业真句（误伤预演）===');
for (const [tag, s] of FP_TESTS) {
  console.log([tag, ppf(s) ? '🔴FP' : 'ok'].join(' | ') + ' | ' + s);
}

