// [v6.7.130 第 300 轮] probe-5-zh-subject：主语域约束的分界线测试
// 纪律：样本只在本文件出现；只报数字与形状。
// probe-4 坐实 8792 判据既有词表组误伤 8/9。本轮测唯一候选判别力来源：
// **主语域** —— 伪哲理的主语是抽象人生域（成熟/成长/强大/幸福…），
// 工程真句的主语是可测量技术实体（延期/指标/对不上/活跃度/拆分/召回率/崩溃/延迟）。
// 注意：8792 判据是 ^[^。！？\n]{0,12}(?:真正)?…不是… 结构，主语跨距只有 12，
// 而工程样本的主语（4-6 字）都落在跨距内 → 需要验证主语约束能否区分。
'use strict';
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const { checkOutput } = require(path.join(ROOT, 'src/gate.js'));

function ppf(t) {
  const r = checkOutput(t);
  return r && r.findings
    ? r.findings.some(f => String(f.dimension || '').indexOf('pseudo_profundity') !== -1)
    : false;
}

// A. 主语域白名单假设：抽象人生域主语 × 既有词表 B 侧 → 应 HIT
const A = [
  ['成熟', '成熟不是终于抵达，是学会与本质共处'],
  ['成长', '成长不是变得世故，是对世界依然保持意义'],
  ['强大', '真正的强大不是无畏，是承认脆弱之后的真相'],
  ['幸福', '幸福不是拥有很多，是计较得很少的自由'],
  ['孤独', '孤独不是缺陷，是灵魂的底色'],
  ['时间', '时间不是敌人，是成长的礼物'],
  ['生命', '生命不是赛跑，是自由的过程'],
];
// B. 技术域主语 × 同一 B 侧 → 当前 8/9 误伤，加主语约束后应 ok
const B = [
  ['延期', '延期不是排期问题，是需求本质还没定'],
  ['指标', '指标下滑不是投放问题，是这次改动意义不大'],
  ['查询', '对不上不是查询错，是数据源才是真相'],
  ['活跃度', '活跃度下降不是推荐问题，是产品成长阶段的正常波动'],
  ['拆分', '这次拆分不是架构问题，是团队自由度不够'],
  ['召回率', '召回率低不是模型问题，是特征才是灵魂'],
  ['崩溃', '崩溃不是内存问题，是连接池才是答案'],
  ['延迟', '延迟不是网络问题，是序列化才是过程'],
];

console.log('=== A. 抽象人生域主语（应 HIT）===');
let aHit = 0;
for (const [tag, s] of A) { const h = ppf(s); if (h) aHit++; console.log([tag, h ? 'HIT' : 'miss'].join(' | ') + ' | ' + s); }
console.log('A_HIT=' + aHit + '/' + A.length);

console.log('=== B. 技术域主语（当前误伤，目标压到 0）===');
let bFp = 0;
for (const [tag, s] of B) { const h = ppf(s); if (h) bFp++; console.log([tag, h ? 'FP' : 'ok '].join(' | ') + ' | ' + s); }
console.log('B_FP=' + bFp + '/' + B.length);

// C. 关键难点：主语跨距只有 12 字，且技术主语常带前缀（「这次」「本次」）
// 测：给技术主语加时间前缀后，主语词是否仍在跨距 12 内可被锚定
const C = [
  ['前缀·这次拆分', '这次拆分不是架构问题，是团队自由度不够'],
  ['前缀·本次延期', '本次延期不是排期问题，是需求本质还没定'],
  ['前缀·这条查询', '这条查询对不上不是语法错，是数据源才是真相'],
  ['前缀·该模块崩溃', '该模块崩溃不是内存问题，是连接池才是答案'],
];
console.log('=== C. 带前缀技术主语（跨距压力测试）===');
for (const [tag, s] of C) console.log([tag, ppf(s) ? 'FP' : 'ok '].join(' | ') + ' | ' + s);

// D. 伪哲理侧主语也可能带前缀/引导词 —— 约束不能把真阳挡掉
const D = [
  ['前缀·真正的强大', '真正的强大不是无畏，是承认脆弱之后的继续'],
  ['前缀·所谓成熟', '所谓成熟不是终于抵达，是学会与不确定共处'],
  ['前缀·真正的幸福', '真正的幸福不是拥有很多，是计较得很少'],
  ['引导·人这一生', '人这一生不是竞赛，是灵魂的底色'],
];
console.log('=== D. 带前缀/引导伪哲理主语（不能被约束挡掉）===');
for (const [tag, s] of D) console.log([tag, ppf(s) ? 'HIT' : 'miss'].join(' | ') + ' | ' + s);
