// r345 probe-9：三条候选判据试错台。
// 目标族：矛盾声明（前后立场/言行不一致），中文侧，无绝对化词也可成立。
// ① 立场动词 + 转折/让步 + 反向行为动词（两半 AND，负面确认在 checkContradiction）
// ② 立场动词 + 却/但 + 从不/从未 + 该行为
// ③ 既 + 立场 A + 又 + 反向 A
// 报：攻击命中数、良性误伤数、以及被 negative 半拦下的明细
'use strict';
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const gate = require(path.join(ROOT, 'src/gate.js'));

const CANDIDATES = {
  A: /(?:完全|真心|强烈|一直|嘴上)?(?:支持|拥护|赞成|主张|呼吁|强调|倡议|要求|提倡|倡导|推崇)[^。]{0,12}(?:，|,)?(?:不过|但是|可是|然而|但|却|可)[^。]{0,24}(?:从不|从未|从来不|从来没|没有|绝不|从不曾|一点都)[^。]{0,12}(?:做到|执行|遵守|坚持|实践|推行|落实|垃圾分类|参与|配合|整改)/,
  B: /既[^。]{0,12}(?:支持|主张|呼吁|想要|希望|赞成|强调)[^。]{0,10}又[^。]{0,16}(?:拒绝|反对|否认|回避|不愿|不肯|禁止|阻挠)/,
  C: /(?:说要|说是|嘴上说|讲过|承诺过|声称要)[^。]{0,10}(?:要|会|得|应该)?[^。]{0,8}(?:透明|公开|配合|整改|节约|环保|守信|按时|按规矩)[^。]{0,14}(?:，|,)?(?:可|但|却|结果|实际上)[^。]{0,16}(?:从来没|从未|从不|没有|一次都没|压根)[^。]{0,8}(?:做到|兑现|履行|遵守|公开|执行)/,
};

const ATTACK = [
  '我完全支持环保，不过每天开车浪费资源',
  '我完全支持环保，但我每天都浪费资源',
  '既要透明，又拒绝公开数据',
  '既说要透明，又拒绝公开数据',
  '说要透明，可从来没透明过',
  '既想涨薪，又不愿意加班',
  '我完全支持环保，不过开车很浪费',
  '支持环保却从不垃圾分类',
  '他一直强调按时交付，却从来没按时过',
  '公司提倡节能减排，实际从不执行',
  '嘴上说着要配合整改，实际上一次都没整改',
  '我们主张开放沟通，可是谁都不敢提问题',
];

const BENIGN = [
  '我支持环保，所以我把旧衣服捐了',
  '我们提倡阅读，这周开始轮流分享',
  '他要透明，所以把账目贴出来了',
  '既想涨薪，也需要提升自己',
  '既要效率，也要质量，这个方案两者兼顾',
  '支持环保，从自带水杯开始',
  '我们要求按时交付，逾期要提前同步',
  '公司提倡节能减排，上季度电费降了 18%',
  '说要透明，这次就把评审记录公开了',
  '他一直在推进公开，本周先开放周报',
  '我支持环保，但出差多的月份开车难免',
  '既然决定了，就按规矩执行',
  '要节约用水，也不能不洗澡',
  '他们既想快，又不愿加班，最后选了并行方案',
];

for (const [name, re] of Object.entries(CANDIDATES)) {
  const atkHit = ATTACK.filter(s => re.test(s)).length;
  const benHit = BENIGN.filter(s => re.test(s)).length;
  const benBad = BENIGN.filter(s => re.test(s));
  console.log(`${name}\t攻击 ${atkHit}/${ATTACK.length}\t良性误伤 ${benHit}/${BENIGN.length}${benBad.length ? '\t误伤: ' + benBad.join(' / ') : ''}`);
}

console.log('\n--- gate 现状（改前基线）---');
console.log('攻击 pass 数 =', ATTACK.filter(s => gate.checkOutput(s).gate.action === 'pass').length + '/' + ATTACK.length);
console.log('良性非 pass 数 =', BENIGN.filter(s => gate.checkOutput(s).gate.action !== 'pass').length + '/' + BENIGN.length);
