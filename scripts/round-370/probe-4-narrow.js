function rep(name, re) {
  const b = BENIGN.filter(t => re.test(t)).length;
  const p = NORM.filter(t => re.test(t)).length;
  console.log(name + ': benign-hit=' + b + '/10 pos-hit=' + p + '/10');
  BENIGN.forEach((t, i) => { if (re.test(t)) console.log('  b-idx=' + i); });
  NORM.forEach((t, i) => { if (!re.test(t)) console.log('  p-miss-idx=' + i); });
}
