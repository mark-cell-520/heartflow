// r393 补腿探针：腿③（ZH 析取对立归责）+ 腿④（结果归因排除）
// 目标：A4「要么接受这个方案，要么就是跟团队过不去」+ A7「方案没成功，说明执行的人能力不行」
// 纪律：先跑攻击命中，再跑良性零误伤，两轮都过才动模块。
const DISJ_BLAME_ZH = /(?:要么|或者|或是)(?:[^，。？！；\n]{0,30}?)[，,](?:要么|或者|或是)(?:[^，。？！；\n]{0,25}?)(?:就是|便是|即是)(?:[^，。？！；\n]{0,25})/;
// 腿④：结果失败锚 × 归因推出锚（排除他因、单推一支）
const RESULT_FAIL_ZH = /(?:没|未|不)(?:能)?(?:成功|奏效|见效|达成|实现|完成|解决问题|拿下|谈成|通过)|(?:失败|落空|告吹|泡汤|受挫|受挫|失手|失策|出错|出问题|有问题|搞砸|搞不定|弄砸)/;
const BLAME_INFER_ZH = /(?:说明|表明|意味着|证明|可见|足见|由此可见|由此可见|归结|归因)(?:[^，。？！；\n]{0,12}?)(?:是|在于|因为)(?:[^，。？！；\n]{0,20})|(?:问题|原因|责任|根源|症结)(?:的)?(?:原因|根源|症结)?(?:就|正|恰恰|必然|肯定|只能)(?:在|是|于)/;

const attacks = [
  '要么接受这个方案，要么就是跟团队过不去',
  '你要么支持这个政策，要么你就是不爱国',
  '你要么同意这个决定，要么就是不在乎公司利益',
  '或者按我说的做，或者就是存心搞砸项目',
  '方案没成功，说明执行的人能力不行',
  '项目失败了，说明市场根本不需要这个产品',
  '谈崩了，说明对方根本没有诚意',
  '实验没出结果，说明这个方向本身是错的',
  '这个季度没达标，说明团队执行力有问题',
  '谈判没谈成，说明我们价格定得太高',
];

const benign = [
  '你要么接受调解，要么就走法律程序，这是两条可选路径',
  '要么今天发布，要么等下周三窗口，两个选项都可以',
  '方案没成功，可能是多方面的原因，需要逐一排查',
  '项目失败了，资金、团队和市场环境都有责任',
  '实验没出结果，我们还得看看是不是设备校准的问题',
  '这个季度没达标，有客观环境的影响，也有策略需要调整的地方',
  '你要么吃面条，要么吃米饭，随便选一个',
  '谈判没谈成，双方都需要再考虑一下',
  '既然不是方案的问题，那可能是执行的人能力不行，当然也要看资源是否充足',
  '开关只有开和关两种状态',
];

let hit = 0;
console.log('=== 腿③（析取对立归责）===');
attacks.slice(0, 4).forEach((t) => {
  const h = DISJ_BLAME_ZH.test(t);
  if (h) hit++;
  console.log((h ? 'HIT ' : 'miss') + ' | ' + t);
});
console.log(`腿③命中 ${hit}/4`);
hit = 0;
console.log('=== 腿④（结果归因排除）===');
attacks.slice(4).forEach((t) => {
  const h = RESULT_FAIL_ZH.test(t) && BLAME_INFER_ZH.test(t);
  if (h) hit++;
  console.log((h ? 'HIT ' : 'miss') + ' | ' + t);
});
console.log(`腿④命中 ${hit}/6`);
let fp = 0;
console.log('=== 良性误伤检查 ===');
benign.forEach((t) => {
  const h3 = DISJ_BLAME_ZH.test(t);
  const h4 = RESULT_FAIL_ZH.test(t) && BLAME_INFER_ZH.test(t);
  if (h3 || h4) fp++;
  console.log((h3 || h4 ? 'FP! ' : 'pass') + ` [l3=${h3} l4=${h4}] | ` + t);
});
console.log(`良性误伤 ${fp}/${benign.length}`);
