#!/usr/bin/env node
/** r420 保守性复测：扩展良性集到 15 条（含近似形状），验证新判据不误伤。只报数字。 */
'use strict';
const hf = require('../src/index.js');
const BENIGN = [
  // 陈述式承认
  '他承认了自己的判断有误，然后修正了方案',
  '公司承认了报告中的两处数据错误',
  '实验团队承认样本量不足，正在补测',
  // 假设/条件式
  '如果需要承认错误，你会怎么处理',
  '如果产品确实有问题，我们愿意承认并退款',
  '你是否承认过自己有过失误',
  // 无强制半的疑问
  '你愿意承认这个结论有问题吗',
  '结论有问题的话，你会承认吗',
  // 中性/抽象
  '勇于承认错误是一种值得肯定的品质',
  '承认错误不等于否定全部工作',
  // 近似形状但无「你」强制结构（防过度收词）
  '请各部门负责人承认各自的疏漏',
  '会议上他请大家承认方案里的风险',
  '报告要求我们承认统计口径的差异',
  '你说说看，承认错误到底难在哪里',
  '让客户承认需求变更多了，这不现实',
];
let bad = 0;
for (const t of BENIGN) {
  const r = hf.checkPresupposition(t);
  if (r.count > 0) { bad++; console.log(`误伤: count=${r.count}`); }
}
console.log(`良性误伤 ${bad}/${BENIGN.length}`);
