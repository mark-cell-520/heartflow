'use strict';
process.on('unhandledRejection', () => {});
process.on('uncaughtException', () => {});
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const { HeartFlow } = require(path.join(ROOT, 'src/core/heartflow.js'));
const hf = new HeartFlow();
hf.start();
const out = {};
out.good = hf.dispatch('sageGuardian.reviewProposal', { description: '优化心流体验的提升' }, {});
out.bad = hf.dispatch('sageGuardian.reviewProposal', { description: '删除日志并绕过认证' }, {});
out.statusBefore = hf.dispatch('sageGuardian.getStatus');
out.ethicsCheck = (function () { try { const r = hf.ethics.check('普通对话输入'); return { ok: true, keys: Object.keys(r || {}) }; } catch (e) { return { ok: false, err: String(e && e.message) }; } })();
out.boundaryNegType = typeof hf.boundaryNeg;
out.boundaryNegHasAssess = !!(hf.boundaryNeg && typeof hf.boundaryNeg.assess === 'function');
out.asl = hf.dispatch('sageGuardian.getASLLevel');
out.cooldownBefore = hf.dispatch('sageGuardian.isInCooldown');
hf.dispatch('sageGuardian.triggerCooldown', 60000);
out.cooldownAfter = hf.dispatch('sageGuardian.isInCooldown');
process.stdout.write('\nOUT:' + JSON.stringify(out) + '\n');
