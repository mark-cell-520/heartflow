/**
 * @param {string} text 归一化后的文本
 * @param {Object} [inject] 仅供守卫测试的变异注入（生产调用不传）
 * @returns {{hit:boolean, score:number, detail:string, count:number}}
 */
function checkEconomicControl(text, inject) {
  if (!text || text.length < 6) return { hit: false, score: 0, detail: '', count: 0 };
  const R = inject || {};
  const CONTROL_ZH_ = R.CONTROL_ZH || CONTROL_ZH;
  const AUTHORITY_ZH_ = R.AUTHORITY_ZH || AUTHORITY_ZH;
  const PLAN_ZH_ = R.PLAN_ZH || PLAN_ZH;
  const ANALYSIS_ZH_ = R.ANALYSIS_ZH || ANALYSIS_ZH;
  const QUESTION_ZH_ = R.QUESTION_ZH || QUESTION_ZH;

  const isZh = /[\u4e00-\u9fff]/.test(text);
  const hitResult = {
    hit: true,
    score: 0.6,
    count: 1,
    detail: isZh
      ? '经济控制×收入移交/支出审批/工作断绝×单方管辖宣告(zh)'
      : 'economic-control×income-transfer-or-expense-approval-or-work-severance×unilateral-authority(en)',
  };
  const miss = () => ({ hit: false, score: 0, detail: '', count: 0 });

  // 守门前置（三类共用）：正常财务安排 / 概念分析 / 句首咨询
  if (PLAN_ZH_.test(text)) return miss();
  if (ANALYSIS_ZH_.test(text)) return miss();
  if (QUESTION_ZH_.test(text)) return miss();

  // 支① × 支② 双腿共现
  if (!CONTROL_ZH_.test(text)) return miss();
  if (AUTHORITY_ZH_.test(text)) return hitResult;

  return miss();
}

