// ─── G4: 句首咨询提问（只认句首咨询词，句中反问追讨不豁免）────────────────
const QUESTION_ZH = new RegExp([
  String.raw`^\s*(?:如何|怎么|怎样|为什么|为何|是否|能不能|可不可以|该不该|要不要|应不应该、该如何)[^。]{0,30}[?？]`,
  String.raw`\b^\s*(?:how|why|what|when|should|is\s+it|can\s+i|do\s+i|does|are\s+there)\b[^.]{0,50}\?`,
].join('|'), 'i');

/**
 * @param {string} text 归一化后的文本
 * @param {Object} [inject] 仅供守卫测试的变异注入（生产调用不传）
 * @returns {{hit:boolean, score:number, detail:string, count:number}}
 */
function checkGuiltInduction(text, inject) {
  if (!text || text.length < 6) return { hit: false, score: 0, detail: '', count: 0 };
  const R = inject || {};
  const SACRIFICE_ZH_ = R.SACRIFICE_ZH || SACRIFICE_ZH;
  const PURSUE_ZH_ = R.PURSUE_ZH || PURSUE_ZH;
  const GRATITUDE_ZH_ = R.GRATITUDE_ZH || GRATITUDE_ZH;
  const ANALYSIS_ZH_ = R.ANALYSIS_ZH || ANALYSIS_ZH;
  const TRIBUTE_ZH_ = R.TRIBUTE_ZH || TRIBUTE_ZH;
  const QUESTION_ZH_ = R.QUESTION_ZH || QUESTION_ZH;

  const isZh = /[\u4e00-\u9fff]/.test(text);
  const hitResult = {
    hit: true,
    score: 0.6,
    count: 1,
    detail: isZh
      ? '内疚诱导×付出标榜×情感追讨(zh)'
      : 'guilt-induction×sacrifice-proclaimed×emotional-pursuit(en)',
  };
  const miss = () => ({ hit: false, score: 0, detail: '', count: 0 });

  // 守门前置（四类共用）：感恩教育 / 概念分析 / 事业奉献 / 句首咨询
  if (GRATITUDE_ZH_.test(text)) return miss();
  if (ANALYSIS_ZH_.test(text)) return miss();
  if (TRIBUTE_ZH_.test(text)) return miss();
  if (QUESTION_ZH_.test(text)) return miss();

  // 支① × 支② 双腿共现
  if (!SACRIFICE_ZH_.test(text)) return miss();
  if (PURSUE_ZH_.test(text)) return hitResult;

  return miss();
}

module.exports = {
  checkGuiltInduction,
  __internals: () => ({
    SACRIFICE_ZH, PURSUE_ZH,
    GRATITUDE_ZH, ANALYSIS_ZH, TRIBUTE_ZH, QUESTION_ZH,
  }),
};
