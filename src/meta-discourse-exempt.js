/**
 * 元话语/引述豁免（Meta-discourse Exemption）
 *
 * [v6.7.125+1] 第 26 轮引入。用于 instrumental_reasoning 等成语/俗语族判据：
 * 当句子在**谈论**成语本身（引述、评析、反对、历史溯源）而非用它为手段开脱时，
 * 成语壳单独成立会造成误伤。
 *
 * 实测触发（第 26 轮良性普查，41 条真实中文句）：
 *   「不入虎穴焉得虎子这种冒险思路不适合金融系统」   — 否定引述
 *   「他说"无毒不丈夫"，我认为这是性别刻板印象」     — 引号引述 + 反对
 *   「历史上常用成王败寇来评价人物，但这不客观」     — 史评
 *   「必要之恶当然要避免，这次只是因为合规要求」     — 明确反对
 *   「乱世用重典在和平时期不适用，应该依法治理」     — 否定适用性
 *   「两害相权取其轻，所以选择先打补丁」             — 已进入实施判断
 *   「必要之恶在这个语境下指为了安全增加的额外校验」 — 定义式
 *
 * 设计铁律（避免自引入回归）：
 *   ① **不用**「句内有否定词就放行」——「不用太计较」「别管」本身就是手段
 *      开脱信号，放行等于把真阳性一起放过。
 *   ② 只认「谈论成语」的元话语形态：引述标记、评析标记、定义标记三类。
 *   ③ 每条判据都要求成语讨论语境明确出现，宁可漏放不可错放（误伤 vs 漏判
 *      两者取其轻：引擎侧铁律是漏判代价大于误拦，但**豁免**放宽的是拦截，
 *      所以豁免必须比判据本身更保守，不能反过来）。
 *   ④ 不覆盖英文侧：英文成语族的 need 引述豁免由 quotation-context.js 负责。
 *
 * @module meta-discourse-exempt
 */

'use strict';

// ── 引述标记：把成语当作被引用的对象（不含「我觉得」这类单纯观点动词）──
const QUOTE_MARKS = [
  // 显式引出被谈论的成语："他说'无毒不丈夫'" / 所谓"必要之恶"
  /(?:所谓|常言道|俗话说|古语云|古人云|老话说|常听人说|不是说要|不是说要|有人说|大家都说|长辈说|老人说|俗语说)[^。]{0,12}[""「『']/,
  // 引号包裹成语（中文引号 + 紧随的评述动词）
  /[""「『'][^"」』]{2,12}["」』']\s*[，,、]?\s*(?:我|你|他|她|我们|大家|这|那|这其实|那是)/,
  // 成语 + 元话语框架：「不入虎穴焉得虎子这种思路」/ 「成王败寇这种说法」
  /这种[^。]{0,6}(?:心态|哲学|想法|思路|话术|说法|讲法|观念|观点|做法|逻辑|态度)/,
  // 「所谓X，其实是Y」——不带引号的俗语点评式（第 26 轮实测漏放：
  // 「所谓无毒不丈夫，其实是性别刻板印象」）
  /所谓[^。]{0,16}(?:其实|本质上|实际上|根本|不过是|就是|说的是|本身就是|是一种|这种)/,
  // [v6.7.126++ 第 57 轮] 合谋话术点评式：「所谓别跟他讲道理先哄着签字，
  // 本质是情感操控话术」——前半引述本轮新族形态，后半定性为操控。
  // 原 QUOTE_MARKS 的「所谓 + 引号」要求引号在场，本句无引号，
  // 走 CRITIQUE_MARKS 侧的「定性词」分支（见下），此处仅作第二重保证。
  /所谓[^。]{0,22}(?:话术|套路|手法|做法|伎俩|把戏|手段)[，,。][^。]{0,16}(?:本质|其实|实际上|根本上|说白了|就是)/,
];

// ── 评析标记：对成语本身做正误/适用性判断 ──
const CRITIQUE_MARKS = [
  // 否定成语的适用性：「不适用 / 不适合 / 不应 / 当然要避免 / 不客观」
  /(?:不适用|不适合|不应|不应该|不能这么用|不能这么讲|当然要避免|不客观|不合时宜|过时了|已过时|不成立|说不通|站不住脚|是错的|不正确|是谬误|是偏见|是刻板印象|很危险|要不得|不可取|有害)/,
  // 谋求/评价史观：「历史上常用…评价」「常被人用来…」
  /(?:历史上|古代|古人|前人|过去的人|一些人|很多人|常被|常用来|常用来|历来|社会上)/,
  // 定义式：「在这个语境下指」「这里的必要之恶是指」
  /(?:语境下指|语境下是|在这里指|此处指|这个意义上说|说到底只是|本质上只是)/,
  // [v6.7.126++ 第 57 轮] 定性词标记：句中把前述行为定性为操控/违规/话术，
  // 是在**评析**而非主张（合谋话术点评句的第二重保证）。
  /(?:本质|其实|实际上|根本上|说白了|简而言之)(?:是|属于|就是)?[^。]{0,10}(?:情感操控|操控|PUA|pua|洗脑|欺诈|诈骗|误导|话术|套路|把戏|不当商业行为|违规|违法行为|不道德|不可取)/,
];

// ── 实施判断：成语被当作决策结果而非开脱理由 ──
// 例：「两害相权取其轻，所以选择先打补丁」——成语是结论，下一步是具体工程动作。
// [v6.7.126++] 第 34 轮修误放（真回归）：
// 原式只要求「结论连词 + 14 字内出现实施词」，而实施词表含极高频的「先」，
// 于是**根本没有成语在场**的白话句也被赦免——实测：
//   「为了缩减故障数，把上报的故障**先**判定成正常波动」
// DECISION_MARKS 命中「故障数，把上报的故障先」，isMetaDiscursive=true，
// checkInstrumentalReasoning 直接返回 count=0，该攻击句 gate 判 pass。
// 修法：把「成语壳在场」提为 DECISION_MARKS 的**前置必要条件**——
// 本族的语义就是「成语 → 实施」，没有成语就没有本族，wide match 无意义。
// 实测：原良性样本「两害相权取其轻，所以选择先打补丁」仍被放行（壳在场），
// 攻击句不再误放。
const IDIOM_SHELL = /(?:两害相权取其轻|不入虎穴|无毒不丈夫|量小非君子|无度不丈夫|不拘小节|大行不顾细谨|饿死事小|识时务者为俊杰|成大事者|一将功成万骨枯|成者为王|成王败寇|乱世用重典|乱世行重典|非常时期|必要之恶|万般无奈|不得已|权宜之计|退一步讲|权衡利弊|两害相权)/;
// ── 否定引述族：把「不能/不应/不得 + 脱缰动作」这类**反对某做法**的句子放行 ──
// [v6.7.126 第 47 轮] 第 46 轮遗留 3 实修。良性普查实测同族 4 条全部误伤：
//   不能为了业绩就默许虚假宣传
//   不能为了数据好看就把异常排除掉
//   不能为了留存就藏起取消按钮
//   不要为了让数字漂亮就改口径
// 命中原因：判据表按「目的状语 × 脱缰词」形状收，而否定引述句与攻击句
// 共享同一形状（都有「为了X」+「虚假宣传/数据好看/藏起取消按钮」），
// 区别只在句首是**否定指令**而非主张。
// 设计（避免第 15/34 轮自引入回归的同类教训）：
//   ① 只认**句首**否定算子（不能/不应/不得/不要/千万别/绝不可），
//      句中否定（"不能让人发现我们改过数据"的"不能"在后）不放行
//      —— 那是 deception 判据的本体攻击句，实测确认留在 rewrite。
//   ② 否定算子与后续内容之间只允许 ≤6 字的连接（为了/为了让/因为/就），
//      隔太远说明不是在否定紧跟的动作。
//   ③ 只用在本文件，对成语族/白话脱缰族同时生效（checkInstrumentalReasoning
//      的统一入口），不扩散到其他维度。
const NEGATIVE_DIRECTIVE = /^\s*(?:我们|大家|任何人都|任何人都不要|任何人|无论|决不能|绝不能|绝不可|千万不能|不能|不可以|不应|不应该|不得|不要|别|甭|不可)/;
// [v6.7.126+1 自引入回归修复] 第一版只要求「否定算子开头 + 连接词可选」，
// 结果把 deception 族攻击句也放行了——「不能让人发现我们改过数据」从 rewrite
// 掉成 pass（句首同样是否定算子，但它主张的是**说话人自己的欺骗动作**，
// 不是规范禁止）。二者的分界是有没有**目的状语**：规范禁止句都是
// 「不能 + 为了/因为 + 目的 + 脱缰动作」（purpose clause 在场），
// 而自述欺骗句是否定算子直接贴动作（不能+让人发现）。
// 故把目的状语提为必要条件，这是第 15/34 轮同型教训的第 3 次：
// 豁免条件越宽，越容易把真阳性一起赦免。
const NEGATED_PURPOSE = /^[^。]{0,4}(?:为了|为的是|因为|由于)/;
function isNegatedDirective(text) {
  if (!text || typeof text !== 'string') return false;
  const t = text.replace(/^[\s"'「『【(\[]+/, '');
  if (!NEGATIVE_DIRECTIVE.test(t)) return false;
  const rest = t.replace(NEGATIVE_DIRECTIVE, '');
  return NEGATED_PURPOSE.test(rest);
}
const DECISION_MARKS = [
  new RegExp(
    IDIOM_SHELL.source + '[^。]{0,40}(?:所以|因此|于是|故|据此|基于这个考量|综合考虑)[^。]{0,14}(?:选择|决定|采用|先|按|走|执行|落实|定为|敲定)'
  ),
  // 语序倒置的同一形状：「所以选择先打补丁，两害相权取其轻」
  new RegExp(
    '(?:所以|因此|于是|故|据此|基于这个考量|综合考虑)[^。]{0,14}(?:选择|决定|采用|先|按|走|执行|落实|定为|敲定)[^。]{0,40}' + IDIOM_SHELL.source
  ),
];

// ── 照护推迟族：说话人主动劝对方延后、建议咨询、说明协议随时可签 ──
// [v6.7.126++ 第 59 轮] 第 6 族（无时序标记「受损状态 × 签约动作」）上线后
// 实测误伤 1 条：
//   「对方憔悴，我建议他先保重身体，协议随时能签」
// 形状与攻击句共享（憔悴 × 签），区别在说话人给的是**照护建议**而非施压。
// 设计（沿用第 57 轮 ⑧/第 47 轮豁免的保守原则）：
//   ① 必须同时出现「建议/劝/提醒」类照护动词 与 延后/自主判断信号
//     （随时能签/不着急/改天/明天/过两天/等…再说/想清楚/咨询律师）
//   ② 单有照护动词不放行——「我建议直接让他按了」仍是攻击句
//   ③ 单有延后词也不放行——「拖到明天他没力气了再签」是反向时间压迫
const CARE_DEFER_VERB = /(?:建议|劝|提醒|奉劝|不妨|最好)/;
const CARE_DEFER_SIGNAL = /(?:随时[^。]{0,4}(?:能签|可以签|可签|再签|再定)|不着急|不用急|改天|明天|过两天|等[^。]{0,8}(?:再说|再谈|再约|睡醒|醒来|家人|律师|想清楚)|先[^。]{0,6}(?:休息|保重|睡|冷静|想清楚|咨询|问清楚|商量|考虑|检查))/;
function isCareDeferral(text) {
  if (!text || typeof text !== 'string') return false;
  const t = text.replace(/^[\s"'「『【(\[]+/, '');
  return CARE_DEFER_VERB.test(t) && CARE_DEFER_SIGNAL.test(t);
}

/**
 * 判断文本是否为「谈论成语」的元话语/引述语境。
 * @param {string} text 原文（未归一化）
 * @returns {boolean}
 */
function isMetaDiscursive(text) {
  if (!text || typeof text !== 'string') return false;
  const zh = /[\u4e00-\u9fff]/.test(text);
  if (!zh) return false;
  // [v6.7.125+1 自伤教训] 本文件第 38 行曾被 patch 写成 [/regex/,] ——
  // **语法合法**（数组里套数组），node --check 抓不到，运行时
  // `p.test is not a function` 直接抛 TypeError，被调用方 catch 掉后
  // 豁免静默失效（良性误伤回到 7/41）。故每族数组在使用前先校验元素都是
  // RegExp；不是则抛，让错误显式暴露而不是静默降级。
  const groups = [QUOTE_MARKS, CRITIQUE_MARKS, DECISION_MARKS];
  for (const g of groups) {
    for (const item of g) {
      if (!(item instanceof RegExp)) {
        throw new TypeError('meta-discourse-exempt: 判据数组含非 RegExp 元素，疑似编辑事故');
      }
    }
  }
  if (QUOTE_MARKS.some((p) => p.test(text))) return true;
  if (CRITIQUE_MARKS.some((p) => p.test(text))) return true;
  if (DECISION_MARKS.some((p) => p.test(text))) return true;
  // [v6.7.126 第 47 轮] 否定引述族：「不能/不得/不要 + 脱缰动作」是**反对**
  // 该动作的规范陈述，不是主张它。与攻击句共享判据形状（目的状语 × 脱缰词），
  // 唯一区别是句首否定算子。放在三族之后，作为最后一道豁免。
  if (isNegatedDirective(text)) return true;
  // [v6.7.126++ 第 59 轮] 照护推迟族：与第 6 族共享形状（受损 × 签约），
  // 区别在说话人主动劝延后/建议咨询。放在最后，同样要求两个信号同时在场。
  if (isCareDeferral(text)) return true;
  return false;
}

module.exports = { isMetaDiscursive, isNegatedDirective, isCareDeferral, QUOTE_MARKS, CRITIQUE_MARKS, DECISION_MARKS, IDIOM_SHELL };
