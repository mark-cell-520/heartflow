/**
 * src/methodology-covariate.js — 方法学「统计控制动词 × 通用协变量」豁免表
 *
 * [r223 立项] 交接簿（data/upgrade-state.json r222 notes）候选①：r221 给
 * checkMoralFoundations 补了「控制动词 + ≤8 字 + 统计对象」紧形状之后，
 * **通用协变量名词**（年龄/收入/背景/性别/学历/地区/健康…）仍整族漏网——
 * r221 刻意没收它们，因为它们是高频日常词，单凭「控制 + 年龄」就豁免会把
 * 「控制人口年龄结构」「控制人民的收入」这类真道德/政治信号一起洗掉。
 * r223 扩样复测（scripts/tmp-223-probe.js）：30 条方法学统计控制句
 * **15 条仍产一条 moral_foundations liberty finding**（severity 20）。
 *
 * 辨别的族：方法学报告里的**协变量控制陈述**——把某个通用协变量（年龄/
 * 收入/家庭背景/性别/病情严重程度…）作为统计对象控制掉，再看效应：
 *   控制年龄之后，两个群体的死亡率差异大幅缩小，说明差距不是由年龄驱动的。
 *   控制了年龄、性别等第三方因素后，暴露与疾病的关联仍然显著。
 *   控制了患者的病情严重程度，两组存活率差异仍然显著。
 * 这句话的「控制」是**统计语义**（control for / adjust for），与
 * 「控制人民/控制媒体/控制资金」的**压迫语义**同名不同义。moral_foundations
 * 的 liberty 通道（/自由|压迫|控制|…/）只认词不认语义，于是每一条方法学
 * 协变量控制句都白送一条 severity 20 的「自由/压迫」finding——该维非
 * action-forcing，单独出现 gate 仍 pass，但与 reasoning_coherence /
 * pseudo_causal 等叠加时就是把良性方法学句推上 verify 的那一条。
 *
 * 与 r221 紧形状表（src/index.js TECH_CONTEXT）的分工——**互补不重叠**：
 *   · r221 表腿③是**统计对象名词**（变量/因素/协变量/混杂/基线/选择偏差…），
 *     收的是「控制X因素」「调整协变量」这类自带统计词尾的形状；
 *   · 本表腿③是**通用协变量名词**（年龄/收入/背景/性别…），收的是
 *     「控制年龄」「调整收入」这类只有裸名词的形状。
 * 两条腿合起来才覆盖方法学协变量控制句的全集；本表刻意不导入 r220
 * STAT_CONTEXT_ZH 的裸统计术语无条件豁免（那边用在道德维度会把
 * 「这项回归分析表明控制者剥夺了人民的自由」的道德信号一起洗掉）。
 *
 * 判据**三腿共现 + 反向守卫，缺一不判**：
 *   腿① COV_ACT_ZH × ≤8 字 × COV_NOUN_ZH——统计控制动词（控制/调整/
 *     校正/纳入/匹配/加权/分层/剔除/排除…）作用于一个通用协变量名词。
 *     与 r221 表同一动词表（对齐，不新增动词，避免放宽攻击面）。
 *   腿② STAT_FRAME_ZH——协变量名词之后 ≤30 字（不跨句末标点）内出现
 *     **统计结论词**（仍然/依然/显著/稳健/效应/差异/系数/估计量/回归/
 *     样本/率/相关/可比/不变…）。这条腿是「统计语义」的实质判据：
 *     r223 实测「控制人口年龄结构，强行规定谁可以生育」（压迫语义）
 *     与「控制人口年龄结构之后，两国的医疗支出差异更能反映制度差别」
 *     （统计语义）**前半句完全相同**，唯一分界就是腿②——前者协变量
 *     之后只有强制动作，后者有统计结论框。
 *   守卫 COERCION_GUARD_ZH——文本出现压迫/政治强制词汇（压迫/奴役/
 *     剥夺/镇压/强制/洗脑/言论/媒体/反抗/暴政/歧视/践踏…）或集体人对象
 *     （人民/民众/群众/百姓/公民/学生/妇女/儿童/老员工/穷人/反对者…）
 *     时整体不豁免。腿②挡得住「无统计结论框」的压迫句，挡不住
 *     「控制收入之后，反抗的声音就显著减弱」这类**用统计外观包装的
 *     压迫陈述**——方法学族永远在估计效应，压迫族永远在压制人，
 *     这条守卫把后者挡在外面（r223 对抗探针实测承重，见测试 C 节）。
 *
 * 为什么反向守卫不收「人口/国家/制度/患者」：r223 实测的方法学句
 * 「在控制人口年龄结构之后，两国的医疗支出差异更能反映制度差别」
 * 「控制了患者的病情严重程度，两组存活率差异仍然显著」本身就含这些词
 * （人口年龄结构是标准协变量、两国比较是标准队列表述、患者是标准医学
 * 队列）——把它们收进守卫会重新制造误伤。守卫只收**动作性压迫词**与
 * **被压制的人**，不收**被统计的人**。
 *
 * 只做 ZH 侧：moral_foundations 的 zh/en 分流按 hasChinese 选表，本表判据
 * 腿全为纯中文正则，EN 文本永不进入（与 r220/r221/r222 同因）。
 */
'use strict';

// ─── 腿①：统计控制动词（中文）────────────────────────────────────────
// 与 r221 TECH_CONTEXT 紧形状表的动词表**逐词对齐**（刻意不新增动词：
// 新增动词等于同时放宽 r221 表与本表的攻击面，要放宽须单独轮次 + A/B）。
const COV_ACT_ZH = /(?:控制|调整|校正|矫正|纳入|加入|考虑|剔除|排除|匹配|加权|分层)/;

// ─── 腿①：通用协变量名词（中文）──────────────────────────────────────
// 方法学报告里被 control for / adjust for 的**非统计词尾**协变量：人口学
// 变量（年龄/性别/学历/婚姻/职业/工龄）、经济社会变量（收入/背景/教育/
// 地区/城乡/成本/价格/利率）、健康与医学变量（健康/病情/剂量/身高/体重）、
// 测量与设计变量（结构/组别/批次/版本/初始/基线/特征/水平/状况/规模/
// 时长/频次/季节/年度/时期/气温/温度/湿度/污染/成绩/经验）。
// 刻意不收：种族/族裔（会被 TECH_CONTEXT 的 STRONG_MORAL 拦死，收了是
// 死代码）、自由/思想/言论/资金/军队/粮食/生育（压迫语义的高频宾语，
// 收了就是攻击面）。
const COV_NOUN_ZH = /(?:年龄|收入|背景|性别|学历|教育|地区|城乡|地域|健康|婚姻|职业|工龄|经验|气温|温度|湿度|剂量|病情|成绩|结构|人数|时长|频次|规模|季节|年度|时期|组别|批次|版本|成本|价格|利率|污染|初始|基线|特征|水平|状况|身高|体重|户籍|住房|资产|支出|消费)/;

// ─── 腿②：统计结论词（中文）──────────────────────────────────────────
// 协变量控制之后出现的**统计/认识论语汇**：稳健性判词（仍然/依然/依旧/
// 还是/显著/稳健/成立/一致/可比/不变）、效应对象（效应/差异/差距/系数/
// 估计量/回归/样本/数据/模型/分析/相关/率/水平/风险/结果/结论/关联/关系/
// 贡献/解释力/波动/趋势/变化/改善/结局/指标/得分/分数/概率/比例/均值/
// 方差/标准差/置信/P值）、比较与判断（比较/公平/合理/可识别）。
// 这条腿是统计语义的实质标记：压迫句（「控制人民的收入，人民就无法
// 反抗」）在协变量之后只有强制动作，永远不出现这些词。
const STAT_CONCL_ZH = /(?:仍然|依然|依旧|还是|显著|稳健|成立|一致|可比|不变|缩小|下降|减弱|恢复|提升|效应|差异|差距|系数|估计量|回归|样本|数据|模型|分析|相关|水平|风险|结果|结论|关联|关系|贡献|解释力|波动|趋势|变化|改善|结局|指标|得分|分数|概率|比例|均值|方差|标准差|置信|比较|公平|合理|可识别|率)/;

// ─── 腿①+② 单正则（保证 动词 → 协变量 → 统计结论 次序）────────────────
// 动词→协变量窗 [^。，,；;！？]{0,8}：只容「了/着/过」与并列定语
//   （「了年龄、性别等第三方」「了这个地区的」），不容分句；
// 协变量→统计结论窗 [^。！？]{0,30}：容逗号（「控制了年龄、性别等第三方
//   因素后，暴露与疾病的关联仍然显著」间距 20 字；「控制了患者的病情严重
//   程度，两组存活率差异仍然显著」间距 16 字），不容句末标点（保证在同一
//   结论句内——「控制人口年龄结构，强行规定谁可以生育」的强制分句因此被
//   挡在外面）。
const COV_METHOD_ZH = new RegExp(
  COV_ACT_ZH.source + '[^。，,；;！？]{0,8}(' + COV_NOUN_ZH.source + ')[^。！？]{0,30}' + STAT_CONCL_ZH.source
);

// ─── 支②：协变量枚举 + 统计对象词尾（无统计结论框的队列表述）──────────
// 「这项研究同时控制了年龄、性别等第三方因素。」——r221 表腿③（因素）与
// 动词间距 10 字 > 8 字窗，本表腿②又要求统计结论框而此句没有（它是纯
// 队列描述，不断言效应）。支②的形状：动词 × ≤16 字 × （因素|变量|
// 协变量|指标），且这 16 字里**必须出现一个通用协变量名词**——
// 「了年龄、性别等第三方」含年龄 ✓；「了社会的稳定」不含任何协变量
// 名词 ✗（「政府控制了社会的稳定因素」这类压迫语义因此不被豁免）。
// 与支①共用同一动词表和反向守卫，攻击面不比支①宽。
const COV_ENUM_ZH = new RegExp(
  COV_ACT_ZH.source +
  '(?=[^。，,；;！？]{0,16}(?:因素|变量|协变量|指标))' +
  '[^。，,；;！？]{0,16}(?:' + COV_NOUN_ZH.source + ')' +
  '[^。，,；;！？]{0,12}(?:因素|变量|协变量|指标)'
);

// ─── 反向守卫：压迫/政治强制词汇 + 被压制的人（中文）────────────────
// r223 对抗探针实测（scripts/tmp-223-probe.js C 组）承重：腿②单独挡不住
// 「控制收入之后，反抗的声音就显著减弱」「调整了年龄结构之后，反对者的
// 数量明显下降」这类**统计外观包装的压迫陈述**——它们有控制动词、有
// 协变量、有统计结论词（显著/下降），三腿齐备。
// 方法学族与压迫族的分界不在形状而在**动作对象**：前者估计效应，后者
// 压制人。守卫只收两类——① 压迫/政治强制动作词；② 被压制的人（集体
// 或个体）。刻意不收「人口/国家/制度/患者/用户/成员/员工」：方法学句
// 本身含这些词（人口年龄结构/两国比较/患者队列/用户分群/样本成员），
// 收了会重新制造 r221 那类误伤（守卫收宽 = 豁免收窄 = 误伤回归）。
const COERCION_GUARD_ZH = /(?:压迫|奴役|剥削|剥夺|镇压|强制|强迫|胁迫|专政|独裁|暴政|专制|极权|洗脑|宣传|言论|媒体|新闻|出版|审查|封锁|禁言|删帖|逮捕|监禁|判刑|处决|屠杀|清洗|迫害|歧视|践踏|侵犯|人权|反抗|抗议|示威|游行|罢工|暴动|革命|颠覆|政权|政府|资金|军队|武器|粮食|生育|老员工|穷人|反对者|异议|记者|律师|学生|妇女|儿童|老人|女性|男性|孩子|下属|人民|民众|群众|百姓|公民|居民|弱势|少数群体)/;

/**
 * 方法学「协变量控制」豁免判定（ZH only，EN 恒 false）。
 *
 * @param {string} text 归一化后的文本
 * @returns {boolean} true = 该句的「控制」是统计语义（control for），
 *                    moral_foundations 的 liberty 通道不应计命中
 */
function hasCovariateMethodology(text) {
  if (!text || typeof text !== 'string') return false;
  // 反向守卫优先：压迫/政治强制语境整体不豁免（守卫宽于判据，先判）
  if (COERCION_GUARD_ZH.test(text)) return false;
  // 腿① × 腿②：统计控制动词作用于通用协变量 + 统计结论框
  if (COV_METHOD_ZH.test(text)) return true;
  // 支②：协变量枚举 + 统计对象词尾（无统计结论框的队列表述）
  return COV_ENUM_ZH.test(text);
}

/**
 * 压迫/政治强制语境守卫（中文）——**控制动词语境豁免的总闸**。
 *
 * 为什么需要单独导出：r221 的紧形状表（src/index.js TECH_CONTEXT）与 r223
 * 本表都收「控制动词 + 统计对象」，而「控制」在中文里同时是**压迫语义的
 * 高频动词**（控制人民/控制资金/控制媒体/控制言论）。r223 对抗探针实测
 * 两条真压迫句穿过 r221 表被误豁免：「政府控制了社会的稳定因素，让所有
 * 异议消失」「控制了穷人的收入因素，他们就没有办法反抗」——形状齐备
 * （控制 + ≤8 字 + 因素），动作对象却是人。形状豁免必须让位于动作对象。
 *
 * 只作控制动词语境豁免的总闸，**不**作用于其余 TECH_CONTEXT 条目
 * （自然语言/独立进程/医学症状/遵守纪律…）：那些条目没有「统计 vs 压迫」
 * 的同名歧义，「学生必须遵守课堂纪律」这类句子的 authority 豁免不能被
 * 本守卫连带打死（r223 实测该句含「学生」，若全局生效会回归）。
 *
 * 收宽/收窄的实测边界：收「政府/政权/人民/民众/群众/百姓/公民/居民/
 * 学生/妇女/儿童/老人/女性/男性/孩子/下属/穷人/弱势/反对者/异议/记者/
 * 律师/老员工」这类**被压制的人**与「压迫/奴役/剥削/剥夺/镇压/强制/强迫/
 * 胁迫/专政/独裁/暴政/专制/极权/洗脑/宣传/言论/媒体/新闻/出版/审查/封锁/
 * 禁言/删帖/逮捕/监禁/判刑/处决/屠杀/清洗/迫害/歧视/践踏/侵犯/人权/反抗/
 * 抗议/示威/游行/罢工/暴动/革命/颠覆/资金/军队/武器/粮食/生育」这类
 * **压迫动作**；**刻意不收**「人口/国家/制度/患者/用户/成员/员工/公司/
 * 企业/学校/医院/团队/样本/队列」——方法学句本身含这些词（人口年龄结构/
 * 两国比较/患者队列/用户分群/样本成员/公司员工），收了会重新制造 r221
 * 那类误伤（守卫收宽 = 豁免收窄 = 误伤回归）。
 *
 * @param {string} text 归一化后的文本
 * @returns {boolean} true = 文本处于压迫/政治强制语境，控制动词语境豁免失效
 */
function hasCoercionContext(text) {
  if (!text || typeof text !== 'string') return false;
  return COERCION_GUARD_ZH.test(text);
}

module.exports = {
  hasCovariateMethodology,
  hasCoercionContext,
  COV_ACT_ZH,
  COV_NOUN_ZH,
  STAT_CONCL_ZH,
  COV_METHOD_ZH,
  COV_ENUM_ZH,
  COERCION_GUARD_ZH,
  __internals: () => ({ COV_ACT_ZH, COV_NOUN_ZH, STAT_CONCL_ZH, COV_METHOD_ZH, COV_ENUM_ZH, COERCION_GUARD_ZH }),
};
