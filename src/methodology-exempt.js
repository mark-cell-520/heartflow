/**
 * src/methodology-exempt.js — 方法学「排除性否定因果归属」豁免表（跨维度共用）
 *
 * [r222 立项] 交接簿（data/upgrade-state.json r221 notes）候选①：r221 给
 * reasoning_coherence 补了 RC_EXCL_NEG_ZH 之后，同一句话族的另外五条误伤
 * 仍挂着——r221 测试 G 节登记的 5 条方法学良性句改后 gate 仍非 pass：
 *   · 「分层之后，各层效应方向一致，说明效应不是由层间差异造成的」
 *     → post_hoc + pseudo_causal（rewrite）
 *   · 「加权之后估计量仍然一致，说明偏差不是由样本结构造成的」
 *     → post_hoc + pseudo_causal（rewrite）
 *   · 「调整了收入因素之后，教育仍然与更高的就业率相关，说明关联不是由
 *     收入造成的」→ cum_hoc + common_cause（rewrite）
 *   · 「控制时间趋势之后，相关关系仍然显著，说明关系不是由共同趋势造成
 *     的」→ cum_hoc + common_cause（rewrite）
 *   · 「排除竞争性解释之后，结论仍然成立，说明结果不是由替代解释造成的」
 *     → mediator_confusion（verify）
 * r222 扩样复测（scripts/tmp-222-probe.js）：30 条方法学排除性否定句
 * **11 条 gate 非 pass、五维合计 25 次命中**（post_hoc 6 / pseudo_causal
 * 12 / cum_hoc 3 / common_cause 3 / mediator_confusion 1）。
 *
 * 辨别的族：方法学报告里的**排除性否定归因**——「在控制/调整/匹配了某个
 * 统计对象之后，效应依然稳健，因此某个替代归因不成立」：
 *   控制年龄之后，两个群体的死亡率差异大幅缩小，说明差距不是由年龄造成的。
 *   工具变量回归之后，结论不变，说明关系不是由反向因果导致的。
 *   增长不能归因于新规。
 * 这句话陈述的是「这个归因不成立」——拒绝无效归因是**正确判别动作**，
 * 与 r216 闸二豁免的「不能据此说/不足以证明」、r221 RC_EXCL_NEG_ZH 同族，
 * 区别只在承载维度：r221 修 reasoning_coherence 一维，本轮收口其余五维
 * （post_hoc / pseudo_causal / cum_hoc / common_cause / mediator_confusion）。
 *
 * 与 r221 RC_EXCL_NEG_ZH（src/index.js）的分工——**刻意不合并**：
 *   · RC_EXCL_NEG_ZH 是 r221 为 reasoning_coherence 第三臂定制的宽表，
 *     主支不收「由」也不要求方法学语境（「差异不是自选择造成的」也豁免），
 *     它的护栏是 r221 F 节：豁免 rc 后 post_hoc/pseudo_causal 仍兜底；
 *   · 本表供**五维共用**，豁免后没有任何其他维度兜底，必须自带更严的
 *     三腿链，否则会把 r221 F 节的边缘攻击和 r220 登记的真后此句一起
 *     放行：
 *       - 「他上任之后利润就涨了，这不是巧合造成的」（r221 F 节）——
 *         无方法学动词、否定与归因间无「由」（巧合不是具名替代原因）；
 *       - 「他坚持早起之后业绩就翻倍，可见早起不是运气造成的」（r221
 *         F 节）——有论断连接词「可见」但无方法学动词、无「由」；
 *       - 「我们调整了排期之后，交付量就稳定了，这不是由巧合造成的」
 *         （r222 A/B 实测的首版漏防攻击）——有方法学动词、有「由」，
 *         但否定归因**不经论断连接词引出**（是独立分句的排除法断言，
 *         不是「说明…不是由…」的方法学结论形）。
 *
 *   支① 三腿链 + 运气对象守卫（单正则，保证次序）：
 *     腿一 METHOD_ACT 方法学动作动词（分层/加权/调整/控制/排除/匹配/
 *       加入/纳入/剔除/标准化/双重差分/工具变量/固定/平减/回归/检验/
 *       校正/安慰剂/倾向得分/分析/估计…）——方法学语境标记；
 *     腿二 ASSERT 论断连接词（说明/表明/可见/证明/意味着/显然/足见），
 *       与腿一间距 ≤40 字（可跨逗号、不可跨句末标点）——标记后面是
 *       **结论句**而不是排除法断言；
 *     腿三 「不是由 Z 造成的」排除性否定归因：否定词 + ≤16 字 + 「由」
 *       + ≤16 字 + 因果归属动词。「由」是必要腿——它标记被否定的**具名
 *       替代原因**（层间差异/收入/替代解释），把「这不是巧合造成的」这类
 *       排除法断言挡在外面；
 *     守卫 Z 不能是运气/巧合类超自然对象（LUCK_OBJECT_ZH）——被否定的
 *       具名原因是运气时，本句是 pseudo_causal 运气归因族的排除法断言
 *       （「可见增长不是由运气带来的」），不是方法学陈述。
 *   支② 归因于否定形：不能/无法/难以/无从 + 归因于/归咎于（「增长不能
 *     归因于新规」）——归因否定的完整习语，无需方法学语境共现。
 *
 * 为什么五维各自早退而不是改判据腿：五个维度的判据形状互不相同（post_hoc
 * 时序连接、cum_hoc 相关×因果、mediator_confusion 控制×效应否定），共同
 * 的只有「这句话在拒绝归因」这一个语义事实；早退豁免与 r220
 * STAT_CONTEXT_ZH 的接入方式一致（函数头判、返回原空结果），不动任何一
 * 维的判据结构，blast radius 可由 A/B 语料逐条证明。
 *
 * 只做 ZH 侧：五维的判据腿（TEMPORAL_CORRELATION / PC_SEQ_ZH /
 * CORRELATION_ZH / CONTROL_ZH）全是纯中文正则，EN 文本永不进这些腿，补 EN
 * 表是死代码（与 r220 STAT_CONTEXT_ZH 只做 ZH 侧同因）。
 */
'use strict';

// ─── 支①腿一：方法学动作动词（中文）────────────────────────────────
// 收方法学/统计设计的标准动作：分层、加权、调整、控制、匹配、剔除……
// 「分析/估计/设定」是统计报告高频词（敏感性分析/效应估计/模型设定），
// 但它们必须与腿二腿三共现才豁免，单出现不豁免。
const METHOD_ACT_ZH = /(?:分层|加权|调整|控制|排除|匹配|加入|纳入|剔除|标准化|归一化|双重差分|工具变量|固定|平减|缩尾|去势|插补|拆分|分组|回归|检验|校正|矫正|安慰剂|倾向得分|替换|重新编码|设定|分析|估计)/;

// ─── 支①腿二：论断连接词（中文）────────────────────────────────────
// 与 r221 的 RC_INFER_ZH 同族：后面跟的是结论句。r222 A/B 实测（首版
// 两条件表）证明这条腿承重——缺了它，「我们调整了排期之后，交付量就
// 稳定了，这不是由巧合造成的」（方法学动词 + 「由」齐备的真后此攻击）
// 会被误豁免，post_hoc 召回掉 1 条。
const ASSERT_CONNECTIVE_ZH = /(?:说明|表明|可见|证明|意味着|显然|足见|足以)/;

// ─── 支①腿三：「不是由 Z 造成的」排除性否定归因（中文）──────────────
// 否定词 + ≤16 字（标点截断）+ 「由」+ ≤16 字（标点截断）+ 因果归属动词。
// 两道标点截断（[^。！？，,；;]）保证「这不是运气，是努力造成的」这类把
// 否定与归因分句的句子不被误豁免——那边的归因是真的。
// 「由」是必要腿：被否定的必须是**具名替代原因**（层间差异/收入/替代解释），
// 而「这不是巧合造成的」否定的巧合不是具名原因，是本族攻击（r221 F 节
// NEG_EDGE 三条）与良性方法学陈述的分界。
// 因果归属动词表覆盖五维 CAUSAL 腿的动词并集（cum_hoc/common_cause/
// mediator_confusion/reasoning_coherence/pseudo_causal 的造成/导致/引起/
// 带来/促使/驱动/决定/推高/解释…），裸词干同时覆盖「…造成的」后缀形。
// r222 首版漏「带来」导致 3 条探针残留误伤（「说明偏差不是由样本结构
// 带来的」），A/B 后补齐——动词表必须与五维 CAUSAL 腿并集对齐，否则
// 漏一个词就是一个残留误伤族。
const EXCL_NEG_BY_ZH = /(?:不是|并非|并不是|绝不是|绝非|不会是|不能是|不应是|难以说是|无法说是)[^。！？，,；;]{0,16}由[^。！？，,；;]{0,16}(?:造成|导致|引起|引发|诱发|催生|促成|酿成|造就|招来|引来|带来|促使|驱动|推动|推升|推高|拉高|抬高|带动|拉动|决定|使得|加剧|加重|滋生|助长|改变|源于|来自|解释|归因)/;

// ─── 支① 三腿链（单正则，保证 方法学动词 → 论断连接词 → 否定归因 次序）──
// 腿一→腿二窗 [^。！？]{0,40}：允许跨逗号（「分层之后，各层效应方向
// 一致，说明…」间距 11 字；「控制年龄之后，两个群体的死亡率差异大幅
// 缩小，说明…」20 字），不许跨句末标点（保证在同一结论句内）。
// 腿二→腿三窗 [^。！？，,；;]{0,16}：连接词与否定词之间只有主语
// （「说明效应不是…」的「效应」），不容逗号分句。
// 捕获组① = 否定归因子句（供运气对象守卫检查被否定的具名原因）。
const EXCL_NEG_METHOD_ZH = new RegExp(
  METHOD_ACT_ZH.source + '[^。！？]{0,40}' + ASSERT_CONNECTIVE_ZH.source +
  '[^。！？，,；;]{0,16}(' + EXCL_NEG_BY_ZH.source + ')'
);

// ─── 运气/超自然对象守卫（支① 第四条件）────────────────────────────
// r222 A/B 实测（补齐「带来」动词后）：两条对抗攻击曾被误豁免——「我们
// 调整了排期之后，交付量仍然在涨，可见增长不是由运气带来的」「他调整了
// 作息之后，业绩仍然在涨，可见增长不是由运气带来的」：方法学动词 × 论断
// 连接词 × 「由」三腿齐备，但被否定的具名原因是**运气**——用排除法断言
// 「不是运气造成的」正是 pseudo_causal 运气归因族（r221 F 节 NEG_EDGE
// 同族：巧合/运气不是统计协变量，是否定它的句子仍在做归因断言）。
// 方法学族否定的永远是统计/认识论对象（层间差异/样本结构/收入/替代解释/
// 遗漏变量/通胀…），永不否定运气——这条守卫把两类分开。
const LUCK_OBJECT_ZH = /运气|巧合|偶然|命运|天意|天命|命数|福气|运势|手气|风水|佛祖|菩萨|老天|老天爷|星座|生肖|八字|命该|运气好/;

// ─── 支②：归因于否定形（中文）────────────────────────────────────
// 「增长不能归因于新规」「差异不能归咎于抽样误差」——归因否定的完整习语，
// 否定词紧贴归因动词，无需方法学语境共现（与 r221 RC_EXCL_NEG_ZH 副支同形）。
const EXCL_NEG_ATTRIB_ZH = /(?:不能|无法|不应|难以|无从|不便)(?:据此|由此|因此|就此)?(?:归因|归罪|归咎)(?:于|到)?/;

/**
 * 方法学「排除性否定因果归属」豁免判定（ZH only，EN 恒 false）。
 * @param {string} text 归一化后的文本
 * @returns {boolean} true = 该句在拒绝无效归因，五维不应判因果族谬误
 */
function hasExclNegCausal(text) {
  if (!text || typeof text !== 'string') return false;
  // 支②：归因于否定形独立成立
  if (EXCL_NEG_ATTRIB_ZH.test(text)) return true;
  // 支①：方法学动词 × 论断连接词 × 「不是由 Z 造成的」三腿链
  const m = EXCL_NEG_METHOD_ZH.exec(text);
  if (!m) return false;
  // 运气对象守卫：被否定的具名原因是运气/巧合类超自然对象时，本句是
  // 运气归因族的排除法断言（攻击形），不豁免（见 LUCK_OBJECT_ZH 注释）
  if (LUCK_OBJECT_ZH.test(m[1])) return false;
  return true;
}

module.exports = {
  hasExclNegCausal,
  METHOD_ACT_ZH,
  ASSERT_CONNECTIVE_ZH,
  EXCL_NEG_BY_ZH,
  EXCL_NEG_METHOD_ZH,
  EXCL_NEG_ATTRIB_ZH,
  LUCK_OBJECT_ZH,
  __internals: () => ({ METHOD_ACT_ZH, ASSERT_CONNECTIVE_ZH, EXCL_NEG_BY_ZH, EXCL_NEG_METHOD_ZH, EXCL_NEG_ATTRIB_ZH, LUCK_OBJECT_ZH }),
};
