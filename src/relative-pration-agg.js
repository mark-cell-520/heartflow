  '(?:别人|人家|其他人|同行|同事|隔壁|大部分(?:人|同行))[^。，！？!?]{0,8}(?:工资|收入|待遇|薪水|报酬|条件|环境|生活|日子)[^。，！？!?]{0,6}(?:比(?:你|你们|咱们)|比你的)[^。，！？!?]{0,6}(?:低|少|差|惨|苦|难)',
