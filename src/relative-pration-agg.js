// ── 腿②族 D：「抱怨什么 X」反问压制（中文）──────────────────────
// 第二人称诉求动词 + 「什么」+ 宾语，疑问收尾——「有什么好抱怨」的同族
// 反问形；宾语指向对方当下诉求。
const RP_DISMISS_QUERY_ZH = [
  /你[^。，！？!?]{0,10}(?:抱怨|吐槽|喊|叫苦|叫累|哭|诉苦|埋怨|发牢骚|嚷嚷|哼|担心|害怕|焦虑|发愁|操心)[^。，！？!?]{0,6}什么/,
  /你[^。，！？!?]{0,10}(?:抱怨|吐槽|喊|叫苦|叫累|哭|诉苦|埋怨|发牢骚|担心|害怕|焦虑|发愁|操心)[^。，！？!?]{0,4}[？?]/,
  // 「这也叫X？」「这也能叫累？」轻蔑反问
  /这(?:也|又)?(?:能?叫|算)[^。，！？!?]{0,6}(?:苦|累|辛苦|困难|难|惨|悲剧|问题)[^。！？!?]{0,4}[？?]/,
  // 「就嚷嚷/就喊累/就叫苦」轻蔑反问（r454 新族）
  /(?:就|也)[^。，！？!?]{0,4}(?:嚷嚷|喊|叫苦|叫累|哭|诉苦|抱怨|吐槽|埋怨)[^。！？!?]{0,4}[？?]/,
  // 「算什么+诉求名词」轻蔑反问（r454 新族）：算什么挫折/算什么苦/算什么累
  /算(?:得上了?|个)什么[^。，！？!?]{0,4}(?:苦|累|辛苦|困难|难|惨|悲剧|问题|挫折|压力|烦恼|事|坎|关|门槛|负担|委屈|不幸)/,
].map((r) => r);

// ── 第六组豁免：正当统计比较 / 事实陈述 ─────────────────────────
// 「我们的排放比十年前下降30%」类正当基线比较、「非洲儿童死亡率下降」
// 类发展报道——无压制诉求腿②时不判（腿②共现已是主防线）；此处收
// **句中明确指向自我改进/研究/政策评估**的统计语境，防止腿②偶然共现
// （如「别抱怨了，来看看我们比去年改善了多少」）。
const RP_AGG_STATS = [
  /比(?:去年|上年|前一阶段|十年前|五年前|去年同|历史)(?:同期)?[^。，！？!?]{0,8}(?:下降|降低|减少|提升|提高|改善|增长)/,
  /(?:同比|环比|较上年|相较于|相比)[^。，！？!?]{0,10}(?:下降|降低|减少|提升|提高|改善)/,
  /(?:儿童|孕产妇|婴儿)?死亡率[^。，！？!?]{0,8}(?:下降|降低|减少|改善)/,
  /(?:人均|平均)[^。，！？!?]{0,6}(?:寿命|收入|gdp|GDP)[^。，！？!?]{0,8}(?:提高|提升|增长|上升)/,
  /(?:研究|数据|统计|报告|调查)[^。，！？!?]{0,6}(?:显示|表明|指出)/,
  /(?:改善|进展|成效|成果)[^。，！？!?]{0,6}(?:显著|明显|可观)/,
  /(?:compared|relative) to (?:last year|the previous|a decade ago|the baseline|five years ago)/i,
  /(?:year-over-year|year on year|quarter-over-quarter)/i,
  /(?:mortality|life expectancy|poverty rate)[^.]{0,20}(?:declined|decreased|improved|rose|increased)/i,
  /(?:study|survey|report|data) (?:shows?|found|indicates?|suggests?)/i,
].map((r) => r);

// [r454] 负例注入要求：常量必须是**模块级可变对象**，函数每次调用读
// 同一引用，测试改 obj.RP_AGG_STATS 才能真实生效。若写成 const 数组
// 直接闭包捕获，测试替换 exports.CONSTANTS.X 无任何作用（实测踩坑）。
const _INJECTABLE = {
  RP_AGG_SUFFER_ZH: RP_AGG_SUFFER_ZH,
  RP_DISMISS_QUERY_ZH: RP_DISMISS_QUERY_ZH,
  RP_AGG_STATS: RP_AGG_STATS,
};

const _any = (arr, text) => arr.some((r) => r.test(text));

/**
 * [r454] 新句式族判别——抽象处境劣势腿① × 反问压制腿②。
 * 与主 checkRelativePrivation 的关系：本函数是**同一维度的新判据族**，
 * 由 index.js 调用点与主判定**取或**合并（max 分），不新增 dimMap 键。
 * @param {string} text 归一化文本
 * @returns {{score: number, name: string, family: string}}
 */
function checkRelativePrivationAgg(text) {
  if (typeof text !== 'string' || text.length === 0) return { score: 0, name: 'relative_pration', family: 'agg', count: 0 };

  // 第六组豁免：正当统计比较/研究陈述。
  if (_any(_INJECTABLE.RP_AGG_STATS, text)) return { score: 0, name: 'relative_pration', family: 'agg', count: 0 };

  // 腿①：抽象处境劣势参照。同时接受**主维度**的腿①命中（具体苦难短语/
  // 负面比较/极小化/英文苦难）——P1「还有人吃不上饭呢，你抱怨什么加班」
  // 的腿①在主维度表中（吃不上），缺的只是腿②反问形，由本族补上。
  const _rp = require('./relative-pration.js').CONSTANTS;
  const sufferHit = _any(_INJECTABLE.RP_AGG_SUFFER_ZH, text)
    || _any(_rp.RP_SUFFER_ZH, text)
    || _any(_rp.RP_COMPARATIVE_ZH, text)
    || _any(_rp.RP_MINIMIZE_HAVE, text)
    || _any(_rp.RP_SUFFER_EN, text)
    || (_any(_rp.RP_SUBJECT_ZH, text) && _any(_rp.RP_WEAK_ZH, text));
  if (!sufferHit) return { score: 0, name: 'relative_pration', family: 'agg', count: 0 };

  // 腿②：本族反问压制形，**或**主维度压制清单——但**显式排除陈述句
  // 压制形 /别[喊叫抱怨吐槽嫌]/（「你租不起房就别抱怨」是陈述句，归主
  // 判定射程；本族只补反问形，r454 实测排除后良性零误伤）。
  const RP_STATEMENT_DISMISS = /别[喊叫抱怨吐槽嫌]/;
  const mainDismissHit = (_any(_rp.RP_DISMISS_ZH, text) || _any(_rp.RP_DISMISS_EN, text))
    && !RP_STATEMENT_DISMISS.test(text);
  const dismissHit = _any(_INJECTABLE.RP_DISMISS_QUERY_ZH, text) || mainDismissHit;
  if (!dismissHit) return { score: 0, name: 'relative_pration', family: 'agg', count: 0 };

  // 双腿共现 → 命中。注意：既有豁免组（RP_SELF_SUFFER/RP_META/RP_TEACH/
  // RP_NEG_FLIP/RP_HEDGE）在 index.js 侧由主判定先行过滤，本函数不再重复，
  // 但 RP_AGG_STATS 是本族新增，必须在此过滤。
  let score = 65;
  if (_any(_INJECTABLE.RP_DISMISS_QUERY_ZH, text)) score += 10;
  const sufferCount = _INJECTABLE.RP_AGG_SUFFER_ZH.filter((r) => r.test(text)).length;
  if (sufferCount >= 2) score += 5;
  if (/[！？!?]/.test(text)) score += 5;
  score = Math.min(score, 90);

  return { score, name: 'relative_pration', family: 'agg', count: 1 };
}

module.exports = {
  checkRelativePrivationAgg,
  // [r454] 可注入常量——测试逐条替换以验证承重（负例注入）。
  CONSTANTS: _INJECTABLE,
};
