  // 群体整体困境短语（非个体具体苦难）
  '饥寒交迫', '民不聊生', '哀鸿遍野', '生灵涂炭', '水深火热', '颠沛流离',
  '吃了上顿没下顿', '衣不蔽体', '食不果腹', '住无所居', '贫病交加',
