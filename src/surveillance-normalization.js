/**
 * @param {string} text 归一化后的文本
 * @param {Object} [inject] 仅供守卫测试的变异注入（生产调用不传）
 * @returns {{hit:boolean, score:number, detail:string, count:number}}
 */
function checkSurveillanceNormalization(text, inject) {
  if (!text || text.length < 6) return { hit: false, score: 0, detail: '', count: 0 };
  const R = inject || {};
  const MONITOR_ZH_ = R.MONITOR_ZH || MONITOR_ZH;
  const REFRAME_ZH_ = R.REFRAME_ZH || REFRAME_ZH;
  const NEUTRAL_ZH_ = R.NEUTRAL_ZH || NEUTRAL_ZH;
  const ANALYSIS_ZH_ = R.ANALYSIS_ZH || ANALYSIS_ZH;
  const GUARDIAN_ZH_ = R.GUARDIAN_ZH || GUARDIAN_ZH;
  const QUESTION_ZH_ = R.QUESTION_ZH || QUESTION_ZH;

  const isZh = /[\\u4e00-\\u9fff]/.test(text);
  const hitResult = {
    hit: true,
    score: 0.6,
    count: 1,
    detail: isZh
      ? '监控正常化×强制监视×关心/信任/安全框定(zh)'
      : 'surveillance-normalization×coerced-monitoring×care/trust/safety-reframe(en)',
  };
  const miss = () => ({ hit: false, score: 0, detail: '', count: 0 });

  // 守门前置（四类共用）：正当隐私讨论 / 概念分析 / 正当监护 / 句首咨询
  if (NEUTRAL_ZH_.test(text)) return miss();
  if (ANALYSIS_ZH_.test(text)) return miss();
  if (GUARDIAN_ZH_.test(text)) return miss();
  if (QUESTION_ZH_.test(text)) return miss();

  // 支① × 支② 双腿共现
  if (!MONITOR_ZH_.test(text)) return miss();
  if (REFRAME_ZH_.test(text)) return hitResult;

  return miss();
}

