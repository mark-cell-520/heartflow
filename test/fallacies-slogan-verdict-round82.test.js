const FALLACY = 'fallacies';

// 取 fallacies 维度的命中数（findings 无 count 字段，severity 即命中信号）
function fallacyCount(text) {
  const r = gate(text);
  const f = (r.findings || []).find(x => x.dimension === FALLACY);
  return f ? (f.severity || 1) : 0;
}
function hasFallacy(text) { return fallacyCount(text) > 0; }

