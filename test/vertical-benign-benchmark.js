const CATEGORIES = {
  '安全': SECURITY,
  '金融': FINANCE,
  '医疗': MEDICAL,
  '法律': LEGAL,
  '教育': EDUCATION,
  '客服': CUSTOMER_SERVICE,
};

function run() {
  const results = [];
  for (const [cat, samples] of Object.entries(CATEGORIES)) {
    for (const text of samples) {
      let action;
      try { action = gate.gate(text).gate.action; } catch (_) { action = 'ERROR'; }
      results.push({ category: cat, text, action, fp: action !== 'pass' });
    }
  }
  return results;
}

function report(results) {
  console.log('\n垂直场景良性基准（预期全部 pass）');
  console.log('─'.repeat(70));
  for (const cat of Object.keys(CATEGORIES)) {
    const rs = results.filter(r => r.category === cat);
    const fp = rs.filter(r => r.fp).length;
    const mark = fp === 0 ? '✅' : `❌ ${fp}`;
    console.log(`  ${cat.padEnd(4)} ${rs.length} 条  ${mark}`);
  }
  const totalFp = results.filter(r => r.fp).length;
  console.log('─'.repeat(70));
  console.log(`  合计 ${results.length} 条 | 误拦 ${totalFp} | 误拦率 ${Math.round(totalFp / results.length * 100)}%`);
  for (const r of results.filter(x => x.fp)) {
    console.log(`  ❌ [${r.category}][${r.action}] ${r.text}`);
  }
  return totalFp === 0;
}

if (require.main === module) {
  const results = run();
  const ok = report(results);
  if (process.argv.includes('--json')) {
    console.log(JSON.stringify({ total: results.length, fp: results.filter(r => r.fp).length, results }, null, 1));
  }
  console.log(ok ? '\n✅ 无回归' : `\n❌ ${results.filter(r => r.fp).length} 条误拦`);
  process.exit(ok ? 0 : 1);
}

module.exports = { run, report, CATEGORIES };
